#!/usr/bin/env python3
"""Token multiple of each coordination workflow (descriptive, point estimates, no test).

Definition: for a coordination workflow W on a run, the token multiple is
    mean total tokens per query of W / mean total tokens per query of the cheapest SC
    configuration (k >= 2) whose point accuracy is at least W's,
i.e. how many times the tokens of an at-least-as-accurate SC configuration W spends.

Runs (the headline runs of Table 1): GSM8K, 500 items x 3 seeds (results/extra/
rev3_reruns_analysis.json, tasks.gsm8k; SC k = 2, 4, 8) and MATH levels 1 to 3, 238 items x 3 seeds,
cap 1,024 (tables/math_easy.json; SC k = 2, 4, 8, 12). HIER is the repaired HIER (HIERFIX_M3 on
GSM8K; on MATH the HIER_M3 records, which are the repaired HIER by the rerun protocol).

Writes paper/arxiv_rev3/token_multiple_macros.tex (\\Tm... macros).
Run: /usr/bin/python3 paper/arxiv_rev3/scripts/emit_token_multiple.py   (from the repository root)
"""
import json, os

HERE = os.path.dirname(os.path.abspath(__file__))
REV3 = os.path.dirname(HERE)
ROOT = os.path.dirname(os.path.dirname(REV3))
GSM = json.load(open(os.path.join(ROOT, "results", "extra", "rev3_reruns_analysis.json")))["tasks"]["gsm8k"]["configs"]
MATH = json.load(open(os.path.join(REV3, "tables", "math_easy.json")))["configs"]

RUNS = {"Gsm": (GSM, ["SC_k2", "SC_k4", "SC_k8"], {"Deb": "DEBATE_N3_R1", "Ge": "GE_R2", "Hier": "HIERFIX_M3"}),
        "Math": (MATH, ["SC_k2", "SC_k4", "SC_k8", "SC_k12"], {"Deb": "DEBATE_N3_R1", "Ge": "GE_R2", "Hier": "HIER_M3"})}
LBL = {"SC_k2": "SC $k{=}2$", "SC_k4": "SC $k{=}4$", "SC_k8": "SC $k{=}8$", "SC_k12": "SC $k{=}12$"}


def multiple(C, sc, w):
    ok = [k for k in sc if C[k]["acc"] >= C[w]["acc"]]
    assert ok, (w, "no SC configuration is at least as accurate")
    k = min(ok, key=lambda x: C[x]["total_tokens"])
    return C[w]["total_tokens"] / C[k]["total_tokens"], k


L = ["% AUTO-GENERATED by paper/arxiv_rev3/scripts/emit_token_multiple.py from",
     "% results/extra/rev3_reruns_analysis.json and tables/math_easy.json. Do not edit.",
     "% Token multiple: mean total tokens of the workflow / mean total tokens of the cheapest SC",
     "% configuration (k >= 2) whose point accuracy is at least the workflow's."]
vals = {}
for run, (C, sc, ws) in RUNS.items():
    for wn, w in ws.items():
        m, k = multiple(C, sc, w)
        vals[(run, wn)] = round(m, 1)
        L.append(f"\\newcommand{{\\Tm{run}{wn}}}{{{m:.1f}}}")
        L.append(f"\\newcommand{{\\Tm{run}{wn}Cmp}}{{{LBL[k]}}}")
        print(f"{run} {w}: {C[w]['total_tokens']:.0f} / {k} {C[k]['total_tokens']:.0f} = {m:.3f}")
v = sorted(vals.values())
L.append(f"\\newcommand{{\\TmMin}}{{{v[0]:.1f}}}")
L.append(f"\\newcommand{{\\TmMax}}{{{v[-1]:.1f}}}")
# Debate on both runs: one value when the two round to the same number.
d = {vals[("Gsm", "Deb")], vals[("Math", "Deb")]}
L.append(f"\\newcommand{{\\TmDeb}}{{{min(d):.1f}}}" if len(d) == 1 else
         f"\\newcommand{{\\TmDeb}}{{{vals[('Gsm', 'Deb')]:.1f} (GSM8K) and {vals[('Math', 'Deb')]:.1f} (MATH)}}")
open(os.path.join(REV3, "token_multiple_macros.tex"), "w").write("\n".join(L) + "\n")
