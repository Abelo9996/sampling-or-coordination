# ========== Holm range for C1 to C4 while C5 is pending
# Holm-adjusted p values are non-decreasing in each raw p, so over every possible C5 p value in
# [0, 1] the adjusted p of C1 to C4 lies between the values at p5 = 0 and p5 = 1 (exact).
def holm(ps):
    m = len(ps); order = sorted(range(m), key=lambda i: ps[i]); adj = [0.0] * m; run = 0.0
    for r_, i in enumerate(order):
        run = max(run, (m - r_) * ps[i]); adj[i] = min(run, 1.0)
    return adj
