def d1(x):
    x = round(x, 1) + 0.0
    return f"{'+' if x > 0 else ''}{x:.1f}"


def tok(x):
    v = int(round(x))
    return ("-" if v < 0 else "") + f"{abs(v):,}".replace(",", "{,}")


def p3(p):
    return "{<}0.001" if p < 0.001 else f"{p:.3f}" if p < 0.1 else f"{p:.2f}"


def peq(p):
    v = p3(p)
    return "p" + (v if v.startswith("{") else "=" + v)


def ivl(lo, hi):
    return f"$[{d1(lo)},{d1(hi)}]$"


def verdict(cheaper, adv):
    """Paper rule. adv[a] = (lo, hi) of sampling minus workflow."""
    if not cheaper:
        return "N", []
    robust = [a for a in cheaper if adv[a][0] > 0]
    if robust:
        return "R", robust
    if all(adv[a][1] < 0 for a in cheaper):
        return "N", []
    return "C", []


