FIGM = FS.macros("figure_macros.tex")
RR = json.load(open(os.path.join(TAB, "review_revision.json")))["tasks"]


# ==== flows (table; replaces the earlier fig_flow diagram) ====
def flow_table():
    """tables/flow_table.tex: for debate and GE, initial answer (debate: round-0 majority; GE:
    first draft) right/wrong against final answer right/wrong, item counts with margins, from
    results/mechanistic.jsonl (trace_counts). Asserted against figure_macros.tex."""
    tc = E.trace_counts()
    d, g = tc["debate"], tc["ge"]
    assert str(d["n"]) == FIGM["flowN"] == str(g["n"])
    assert str(d["kept"] + d["fix"]) == FIGM["flowDebFinal"]
    assert str(g["kept"] + g["fix"]) == FIGM["flowGeFinal"]
    assert f"{100 * (d['kept'] + d['fix']) / d['n']:.1f}" == FIGM["flowDebFinalPct"]
    assert f"{100 * (g['kept'] + g['fix']) / g['n']:.1f}" == FIGM["flowGeFinalPct"]

    def cells(x, row):
        if row == "right":
            return [x["kept"], x["cor"], x["kept"] + x["cor"]]
        if row == "wrong":
            return [x["fix"], x["still"], x["fix"] + x["still"]]
        return [x["kept"] + x["fix"], x["cor"] + x["still"], x["n"]]
    L = ["% AUTO-GENERATED by paper/arxiv_rev3/scripts/make_fig_eaai_adapted.py (flow_table) from",
         "% results/mechanistic.jsonl: rows initial answer, columns final answer, item counts. Do not edit.",
         "% Columns: initial | debate: final right, final wrong, total | GE: final right, final wrong, total"]
    for row, lab in (("right", "Initially right"), ("wrong", "Initially wrong"), ("total", "Total")):
        if row == "total":
            L.append("\\midrule")
        L.append(" & ".join([lab] + [str(v) for v in cells(d, row) + cells(g, row)]) + " \\\\")
    open(os.path.join(TAB, "flow_table.tex"), "w").write("\n".join(L) + "\n")
    return tc


# ==== criterion ====
CRIT_W = 0.8 * FS.FULL_W


def draw_criterion(ax, az, pts, ylim=(0.1, 300)):
    """Main panel: log p_fix/p_cor against base accuracy; az: the 'ratio = 0' strip below a
    broken axis. A ratio of 0 (no item fixed) and an interval end at 0 are drawn in the strip; an
    interval that runs below the log panel continues across the break as an arrow."""
    a = np.linspace(0.5, 0.99, 400)
    be = a / (1 - a)
    ax.plot(a, be, color="black", lw=FS.LW, zorder=2)
    ax.set_yscale("log")
    ax.set_xlim(0.5, 0.99)
    ax.set_ylim(*ylim)
    ax.axhline(1.0, color="#555555", lw=0.8, ls=":", zorder=1)
    # direct labels (curve and reference line) and small grey region notes
    ax.text(0.70, 3.2, r"break-even $a/(1-a)$", ha="right", va="bottom", color="black")
    ax.text(0.975, 0.92, r"$p_{\mathrm{fix}} = p_{\mathrm{cor}}$", ha="right", va="top", color="#555555")
    ax.text(0.505, 60, r"coordination helps ($\Delta > 0$)", ha="left", va="center", color=FS.MUTED,
            style="italic")
    ax.text(0.505, 0.2, r"coordination hurts ($\Delta < 0$)", ha="left", va="center", color=FS.MUTED,
            style="italic")
    az.set_ylim(-1, 1)
    az.set_yticks([0])
    az.set_yticklabels(["0"])
    az.grid(False, axis="y")
    for p in pts:
        c = COL[p["topo"]]
        mk = FS.MARK[p["topo"]]
        x = p["a"] * p["jit"]
        lo, hi = p["ratio_ci"]
        tgt, y = (az, 0.0) if p["ratio"] == 0 else (ax, p["ratio"])
        if p["ratio"] > 0:
            if lo > ylim[0]:
                FS.errorbar(ax, x, y, lo, hi, color=c, marker="none")
            else:   # lower end below the log panel: arrow to the break, cap at 0 in the strip
                FS.errorbar(ax, x, y, y, hi, color=c, marker="none")
                ax.annotate("", xy=(x, ylim[0]), xytext=(x, y), zorder=3,
                            arrowprops=dict(arrowstyle="-|>", color=c, lw=FS.ELW, mutation_scale=7,
                                            shrinkA=0, shrinkB=0))
                if lo == 0:
                    az.plot([x, x], [0, 1], color=c, lw=FS.ELW, zorder=3, clip_on=False)
                    az.plot([x], [0], "_", color=c, ms=2 * FS.CAPSIZE, mew=FS.ELW, zorder=3)
        FS.errorbar(tgt, x, y, color=c, marker=mk, mfc=p["mfc"], xlo=p["a_ci"][0], xhi=p["a_ci"][1],
                    zorder=4)
    # broken-axis marks on the left spine
    d = dict(marker=[(-1, -0.6), (1, 0.6)], markersize=6, linestyle="none", color="black",
             mec="black", mew=0.6, clip_on=False)
    ax.plot([0], [0], transform=ax.transAxes, **d)
    az.plot([0], [1], transform=az.transAxes, **d)
    ax.spines["bottom"].set_visible(False)
    ax.tick_params(axis="x", which="both", bottom=False, labelbottom=False)
    az.set_xlabel(r"base accuracy $a$")
    ax.set_ylabel(r"$p_{\mathrm{fix}}\,/\,p_{\mathrm{cor}}$ (log scale)")


def fig_criterion():
    pts = E.criterion_points()
    assert [p["ratio"] == 0 for p in pts] == [False, False, True] and pts[1]["ratio_ci"][0] == 0
    fig, (ax, az) = plt.subplots(2, 1, figsize=(CRIT_W, 3.3), sharex=True,
                                 gridspec_kw=dict(height_ratios=[7, 1]))
    fig.get_layout_engine().set(hspace=0.0, h_pad=0.01)
    draw_criterion(ax, az, pts)
    hs = [Line2D([], [], color=COL[p["topo"]], marker=FS.MARK[p["topo"]], mfc=p["mfc"],
                 ms=FS.MS, ls="none",
                 label=f"{p['lab']}: {p['fix']}/{p['wrong']} vs {p['cor']}/{p['right']}")
          for p in pts]
    fig.legend(handles=hs, loc="outside upper center", ncol=2)
    FS.save(fig, "fig_criterion")
    return pts


# ==== code energy and engineering frontier ====
def check_cfg(task, agg, extra=None):
    js = RR[task]["configs"]
    assert set(agg) == set(js), (task, set(agg) ^ set(js))
    for c, a in agg.items():
        assert abs(a["accuracy"] * 100 - js[c]["acc"]) < 1e-9, (task, c)
        assert abs(a["tokens"] - js[c]["total_tokens"]) < 1e-6, (task, c)
        if extra:
            assert abs(extra[c] - js[c]["energy_j"]) < 1e-6, (task, c)


def label_items(agg, keys):
    """Sampling points labeled SA, k=2, ... in text color; workflows by name in their color."""
    out = []
    for c in keys:
        t = E.topo_of(agg[c])
        if t in ("SA", "SC"):
            out.append((FS.klabel(c), agg[c]["tokens"], agg[c]["accuracy"] * 100, FS.TEXT))
        else:
            out.append((FS.NAME[c], agg[c]["tokens"], agg[c]["accuracy"] * 100, COL[t]))
    return out


def fig_code_energy():
    from collections import defaultdict
    rows = E.load("humaneval_matrix_pc.jsonl")
    agg = E.analyze.aggregate(rows)
    main = ["SA", "SC_k2", "SC_k4", "SC_k8", "DEBATE_N3_R1", "GE_R2", "HIER_M3"]
    agg = {c: agg[c] for c in main}
    en = defaultdict(lambda: defaultdict(list))
    for r in rows:
        en[r["config"]][r["item_id"]].append(r["energy_j"])
    joules = {c: float(np.mean([np.mean(v) for v in en[c].values()])) for c in main}
    check_cfg("code", agg, joules)
    agg_e = {c: dict(agg[c], tokens=joules[c]) for c in main}
    fig, axes = plt.subplots(1, 2, figsize=(FS.FULL_W, 2.85), sharey=True)
    hulls = {}
    for ax, A, xl, key in ((axes[0], agg, "total tokens per query (log scale)", "tokens"),
                           (axes[1], agg_e, "gross GPU energy per query, J (log scale)", "joules")):
        hulls[key] = E.frontier_panel(ax, A, xpad=(0.72, 1.5))
        ax.set_xlabel(xl)
        ax.set_ylim(40, 80)
    axes[0].set_ylabel("pass@1 (%)")
    fig.legend(handles=E.legend_handles(), loc="outside upper center", ncol=6)
    probs = []
    for ax, A in ((axes[0], agg), (axes[1], agg_e)):
        texts = E.place_labels(ax, label_items(A, main), fontsize=FS.FONT_PT, pad=1.0, max_d=60,
                               cross_pen=200)
        probs += E.check_labels(ax, texts, pad=0.2)
    assert not probs, probs
    FS.save(fig, "fig_code_energy")
    return hulls


def fig_proeng_pareto():
    agg, _ = E.agg_task("mmlu_pro_eng")
    check_cfg("proeng", agg)
    # error bars: the accuracy intervals of Table 1 and tab:proeng (scripts/item_ci.py; B = 10,000,
    # seed 0), not the B = 2,000 intervals of harness.analyze.aggregate
    for c, a in agg.items():
        d = rr_config("proeng", c)
        assert f"{a['accuracy'] * 100:.1f}" == f"{d['acc']:.1f}", (c, a["accuracy"], d["acc"])
        agg[c] = dict(a, acc_lo=d["lo"] / 100, acc_hi=d["hi"] / 100)
    fig, ax = plt.subplots(figsize=(0.75 * FS.FULL_W, 3.0))
    hull = E.frontier_panel(ax, agg, xpad=(0.8, 1.6))
    names = {"SA": "SA", "SC_k2": "SC $k{=}2$", "SC_k4": "SC $k{=}4$", "SC_k8": "SC $k{=}8$"}
    assert ", ".join(names[c] for c in hull) == FIGM["mixFrontierProEng"], hull
    ax.set_ylim(15.5, 42.5)
    ax.set_xlabel("total tokens per query (log scale)")
    ax.set_ylabel("accuracy (%)")
    fig.legend(handles=E.legend_handles(), loc="outside upper center", ncol=3)
    keys = ["SA", "SC_k2", "SC_k4", "SC_k8", "DEBATE_N3_R1", "HIER_M3", "GE_R2"]
    # beside the marker if free, else in the point's own column beyond its error bar (vertical
    # leader along nothing but empty space), so no label or leader crosses another bar
    items = [(txt, x, y, agg[c]["acc_lo"] * 100, agg[c]["acc_hi"] * 100, col)
             for (txt, x, y, col), c in zip(label_items(agg, keys), keys)]
    texts = E.place_in_column(ax, items, fontsize=FS.FONT_PT, dirs=(-1, 1), side_r=5.8)
    probs = E.check_labels(ax, texts, pad=0.2)
    assert not probs, probs
    FS.save(fig, "fig_proeng_pareto")
    return hull


# ==== criterion-units table (replaces fig_criterion_units) ====
def tex_int(v):
    return f"{int(v):,}".replace(",", "{,}")


def tex_num(v):
    if math.isinf(v):
        return r"$\infty$"
    return f"{v:.1f}"


def criterion_units_table():
    pts = E.criterion_points(("ge_item", "ge_rev", "item70", "agent70", "debate_item"))
    u = {p["key"]: p for p in pts}
    assert f"{u['agent70']['ratio']:.1f}" == FIGM["unitRatioAgentSev"], u["agent70"]["ratio"]
    assert f"{u['item70']['ratio']:g}" == FIGM["unitRatioItemSev"], u["item70"]["ratio"]
    lab = {"debate_item": "3B debate, per item", "ge_item": "3B GE, per item",
           "ge_rev": "3B GE, per revision opportunity", "item70": "70B debate, per item",
           "agent70": "70B debate, per agent"}
    L = ["% AUTO-GENERATED by paper/arxiv_rev3/scripts/make_fig_eaai_adapted.py (criterion_units_table)",
         "% from results/mechanistic.jsonl and results/gsm8k_llama70b.jsonl with the unit clusters and",
         "% summarize() of scripts/make_eaai_figures.py (95% item-cluster percentile bootstrap,",
         "% B=10,000, seed 0); replaces fig_criterion_units. Rows only. Do not edit.",
         "% Suggested: \\begin{tabular}{lrrrl} \\toprule",
         "% Unit & Fixed / initially wrong & Corrupted / initially right & $p_{\\mathrm{fix}}/p_{\\mathrm{cor}}$ & 95\\% interval \\\\ \\midrule"]
    for k in ("debate_item", "ge_item", "ge_rev", "item70", "agent70"):
        p = u[k]
        lo, hi = p["ratio_ci"]
        L.append(f"{lab[k]} & {tex_int(p['fix'])} / {tex_int(p['wrong'])} & "
                 f"{tex_int(p['cor'])} / {tex_int(p['right'])} & {tex_num(p['ratio'])} & "
                 f"[{tex_num(lo)}, {tex_num(hi)}] \\\\")
    open(os.path.join(TAB, "criterion_units_table.tex"), "w").write("\n".join(L) + "\n")
    return {k: (u[k]["fix"], u[k]["wrong"], u[k]["cor"], u[k]["right"], u[k]["ratio"],
                u[k]["ratio_ci"]) for k in u}


def main():
    print("flow_table:", flow_table())
    print("fig_criterion:", [(p["lab"], p["fix"], p["wrong"], p["cor"], p["right"],
                              round(p["ratio"], 3)) for p in fig_criterion()])
    print("fig_code_energy hulls:", fig_code_energy())
    print("fig_proeng_pareto hull:", fig_proeng_pareto())
    print("criterion_units_table:", criterion_units_table())


if __name__ == "__main__":
    main()
