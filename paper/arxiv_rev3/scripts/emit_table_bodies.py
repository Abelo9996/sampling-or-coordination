#!/usr/bin/env python3
"""rev3: the tabular of each generated whole-table fragment, for the merged tables of the paper.

Some generated fragments in tables/rev3/ are complete table environments (caption, label and
tabular). The merged tables of main.tex and appendix.tex combine several of them under one
caption, so they need the tabular alone. For each fragment below this script copies the text
from \\begin{tabular} to \\end{tabular}, byte for byte, into tables/rev3/tabular_<name>.tex. No
cell is changed or recomputed.

It also writes tables/rev3/equivalence_orig_rows.tex: the rows of equivalence_table.tex (gain
bounds of the original runs) without its GSM8K-200 block, which the merged gain-bound table
already prints from rr_equivalence.tex; the script asserts that the two GSM8K-200 rows are equal.

Run after scripts/emit_rev3_tables.py and scripts/emit_rev3_reruns.py (scripts/build.sh does).
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
DST = os.path.join(os.path.dirname(HERE), "tables", "rev3")
FRAGMENTS = ["trunc_table", "scale_table", "diversity_table", "latency_table",
             "criterion_predictive_table", "criterion_splits_table", "criterion_pooled_table",
             "rr_orig_humaneval_table", "rr_orig_humaneval_supp_table", "mmlu_pro_eng_table",
             "rr_throughput_table", "positioning_table"]


def main():
    for name in FRAGMENTS:
        t = open(os.path.join(DST, name + ".tex")).read()
        assert t.count("\\begin{tabular}") == 1 and t.count("\\end{tabular}") == 1, name
        a = t.index("\\begin{tabular}")
        b = t.index("\\end{tabular}") + len("\\end{tabular}")
        body = t[a:b]
        assert re.search(r"\d", body), name
        open(os.path.join(DST, f"tabular_{name}.tex"), "w").write(
            f"% AUTO-GENERATED by scripts/emit_table_bodies.py: the tabular of tables/rev3/{name}.tex, unchanged.\n"
            + body + "\n")
    # gain bounds of the original runs, without the GSM8K-200 block printed in the upper block
    eq = open(os.path.join(DST, "equivalence_table.tex")).read().split("\\midrule")
    g200 = [b for b in eq if b.strip().startswith("GSM8K-200")]
    assert len(g200) == 1
    rr = [l for l in open(os.path.join(DST, "rr_equivalence.tex")).read().splitlines() if l.startswith("GSM8K-200")]
    assert rr == [g200[0].strip()], (rr, g200)
    rest = "\\midrule".join(b for b in eq if b is not g200[0])
    lines = [l for l in rest.splitlines() if not l.startswith("%")]
    open(os.path.join(DST, "equivalence_orig_rows.tex"), "w").write(
        "% AUTO-GENERATED by scripts/emit_table_bodies.py: equivalence_table.tex without its GSM8K-200 block "
        "(equal to the GSM8K-200 row of rr_equivalence.tex).\n" + "\n".join(lines).strip("\n") + "\n")
    print("wrote", len(FRAGMENTS), "tabular files and equivalence_orig_rows.tex")


if __name__ == "__main__":
    main()
