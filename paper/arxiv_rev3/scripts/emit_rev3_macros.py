#!/usr/bin/env python3
"""rev3: macros for the statistics reframing and the quotable numbers, read from existing outputs.

No test is recomputed. Each value is read from a JSON that an earlier analysis wrote, and printed
with the formatting conventions of the rev2 macro files:
  tables/review_revision.json (copy of paper/arxiv_long/tables/review_revision.json):
      unadjusted hierarchical-bootstrap p of every exploratory SC k=8 (and HumanEval SA) versus
      coordination comparison (tasks.<t>.tests["SC_k8|W"].p), replacing the Holm values rev2
      printed; token means behind the price-ratio crossover.
  data/pareto_membership.out (copy of paper/arxiv_long/scripts/pareto_membership.out): share of
      10,000 seed-aware resamples in which each GSM8K configuration is non-dominated.
  results/extra/hard_math_analysis.json: unadjusted p of the output-token comparisons on MATH
      levels 4 to 5 (rev2 printed Holm values for this exploratory family).
Asserts: the Holm values rev2 printed are reproduced from the same JSON entries (so the
unadjusted value is the right partner), the crossovers round to 7.97 and 5.68 (rev2 text), and
the membership shares round to the rev2 text (100, 91, 84, 6, at most 2, below 0.1).
Writes paper/arxiv_rev3/rev3_macros.tex.
"""
import json, os, re

HERE = os.path.dirname(os.path.abspath(__file__))
REV3 = os.path.dirname(HERE)
ROOT = os.path.dirname(os.path.dirname(REV3))

RR = json.load(open(os.path.join(REV3, "tables", "review_revision.json")))["tasks"]
MEM = json.load(open(os.path.join(REV3, "data", "pareto_membership.out")))
HM = json.load(open(os.path.join(ROOT, "results", "extra", "hard_math_analysis.json")))
MAC = {}
for f in os.listdir(REV3):
    if f.endswith("_macros.tex") and f not in ("rev3_macros.tex",):
        for m in re.finditer(r"\\newcommand\{\\(\w+)\}\{(.*)\}", open(os.path.join(REV3, f)).read()):
            MAC[m.group(1)] = m.group(2)

W = {"DEBATE_N3_R1": "Deb", "GE_R2": "Ge", "HIER_M3": "Hier"}
T = {"gsm8k": "Gsm", "math": "Math", "mmlu": "Mmlu", "proeng": "Eng", "code": "Code", "gsm8k200": "Gsmtwo"}
L = ["% AUTO-GENERATED by paper/arxiv_rev3/scripts/emit_rev3_macros.py. Do not edit."]


def mac(n, v):
    L.append(f"\\newcommand{{\\{n}}}{{{v}}}")


def p3(p):
    """rev2 convention: <0.001, three decimals below 0.1, two decimals otherwise."""
    return "{<}0.001" if p < 0.001 else f"{p:.3f}" if p < 0.1 else f"{p:.2f}"


# 1. Unadjusted p, SC k=8 minus each coordination workflow (exploratory families).
for t, tn in T.items():
    tests = RR[t]["tests"]
    for w, wn in W.items():
        k = f"SC_k8|{w}"
        if k in tests:
            mac(f"RthP{tn}{wn}", p3(tests[k]["p"]))
            mac(f"RthPr{tn}{wn}", p3(tests[k]["p"]) if p3(tests[k]["p"]).startswith("{") else "{=}" + p3(tests[k]["p"]))
    if t == "code":
        for w, wn in W.items():
            mac(f"RthPSa{tn}{wn}", p3(tests[f"SA|{w}"]["p"]))
            v = p3(tests[f"SA|{w}"]["p"]); mac(f"RthPrSa{tn}{wn}", v if v.startswith("{") else "{=}" + v)
# Holm values rev2 printed come from the same entries (sanity: Holm over the three p reproduces them).
def holm(ps):
    m = len(ps); order = sorted(range(m), key=lambda i: ps[i]); adj = [0.0] * m; run = 0.0
    for r, i in enumerate(order):
        run = max(run, (m - r) * ps[i]); adj[i] = min(run, 1.0)
    return adj
for t in ("gsm8k", "math", "mmlu", "proeng", "code"):
    ps = [RR[t]["tests"][f"SC_k8|{w}"]["p"] for w in W]
    adj = holm(ps)
    for w, a in zip(W, adj):
        assert abs(a - RR[t]["holm_declared"]["SC_k8"][w]) < 1e-9, (t, w)
assert MAC["XtrEngScDebHolm"] == f"{RR['proeng']['holm_declared']['SC_k8']['DEBATE_N3_R1']:.3f}"
assert MAC["pHolmGeCode"] == "{=}" + f"{RR['code']['holm_declared']['SC_k8']['GE_R2']:.3f}"
# Table 1 caption of rev2: Holm 0.036/0.046/<0.001 (GSM8K), 0.096/0.052/0.016 (MATH), MMLU >= 0.43.
assert [round(RR["gsm8k"]["holm_declared"]["SC_k8"][w], 3) for w in W][:2] == [0.036, 0.046]
assert [round(RR["math"]["holm_declared"]["SC_k8"][w], 3) for w in W] == [0.096, 0.052, 0.016]
mac("RthPMmluMin", f"{min(RR['mmlu']['tests'][f'SC_k8|{w}']['p'] for w in W):.2f}")

# 2. Price-ratio crossover: SC k=8 is cheaper than debate in input + r x output tokens iff r < r*.
ME = json.load(open(os.path.join(REV3, "tables", "math_easy.json")))["configs"]
s8, dd = ME["SC_k8"], ME["DEBATE_N3_R1"]
r238 = ((dd["total_tokens"] - dd["out_tokens"]) - (s8["total_tokens"] - s8["out_tokens"])) / (s8["out_tokens"] - dd["out_tokens"])
assert f"{r238:.2f}" == "5.27", r238   # independent audit recomputed 5.27 from the records
mac("RthCrossMath", f"{r238:.2f}")
mac("RthCrossRoundMath", f"{r238:.1f}")
for t, tn in (("gsm8k", "Gsm"), ("math", "MathSixty")):
    s, d = RR[t]["configs"]["SC_k8"], RR[t]["configs"]["DEBATE_N3_R1"]
    ins, ind = s["total_tokens"] - s["out_tokens"], d["total_tokens"] - d["out_tokens"]
    r = (ind - ins) / (s["out_tokens"] - d["out_tokens"])
    mac(f"RthCross{tn}", f"{r:.2f}")
    mac(f"RthCrossRound{tn}", f"{r:.1f}")
assert MAC.get("RthCrossGsm") is None
assert f"{(lambda s, d: ((d['total_tokens'] - d['out_tokens']) - (s['total_tokens'] - s['out_tokens'])) / (s['out_tokens'] - d['out_tokens']))(RR['gsm8k']['configs']['SC_k8'], RR['gsm8k']['configs']['DEBATE_N3_R1']):.2f}" == "7.97"
assert f"{(lambda s, d: ((d['total_tokens'] - d['out_tokens']) - (s['total_tokens'] - s['out_tokens'])) / (s['out_tokens'] - d['out_tokens']))(RR['math']['configs']['SC_k8'], RR['math']['configs']['DEBATE_N3_R1']):.2f}" == "5.68"

# 3. Frontier membership over seed-aware resamples (GSM8K, eleven configurations).
mac("RthMemSa", f"{MEM['SA']:.0f}")
mac("RthMemSceight", f"{MEM['SC_k8']:.0f}")
mac("RthMemScfour", f"{MEM['SC_k4']:.0f}")
mac("RthMemBestCoord", f"{max(MEM[k] for k in MEM if not k.startswith(('SA', 'SC'))):.0f}")
mac("RthMemDebMax", f"{max(MEM['DEBATE_N2_R1'], MEM['DEBATE_N3_R1']):.0f}")
mac("RthMemNConfigs", str(len(MEM)))
assert (MEM["SA"], round(MEM["SC_k8"]), round(MEM["SC_k4"]), round(MEM["GE_R1"])) == (100.0, 91, 84, 6)
assert max(MEM[k] for k in MEM if not k.startswith(("SA", "SC"))) == MEM["GE_R1"]
assert round(max(MEM["DEBATE_N2_R1"], MEM["DEBATE_N3_R1"])) == 2 and max(MEM["HIER_M2"], MEM["HIER_M3"]) < 0.1
assert len(MEM) == 11

# 4. MATH levels 4 to 5, output-token comparisons (exploratory): unadjusted p.
for w, wn in W.items():
    r = HM["output_tokens"][w]
    mac(f"RthHmPOut{wn}", "p{<}0.001" if r["p"] < 0.001 else f"p={r['p']:.3f}" if r["p"] < 0.01 else f"p={r['p']:.2f}")
    holm_txt = "p{<}0.001" if r["p_holm"] < 0.001 else f"p={r['p_holm']:.3f}" if r["p_holm"] < 0.01 else f"p={r['p_holm']:.2f}"
    assert MAC[f"HmPOut{wn}"] == holm_txt, (w, MAC[f"HmPOut{wn}"], holm_txt)

# 4b. MATH levels 1 to 3 (238 items): one-sided 95% bound on the gain over SC k=8 (upper limit of
#     the 90% hierarchical interval), from results/extra/math_interaction_analysis.json.
MI = json.load(open(os.path.join(ROOT, "results", "extra", "math_interaction_analysis.json")))
for w, wn in W.items():
    r = MI["within_stratum"][w]["easy_minus_SC_k8"]
    up = round(r["ci90"][1], 1) + 0.0
    mac(f"RthEasyUp{wn}", f"${'+' if up > 0 else ''}{up:.1f}$")
    assert (r["ci90"][1] < 0) == (r["p_any_gain"] < 0.05)
open(os.path.join(REV3, "rev3_macros.tex"), "w").write("\n".join(L) + "\n")
print("\n".join(L))

# 5. Thousands separators for generated macros whose value is a bare integer of four or more
#    digits (formatting only; the value is unchanged). Written to rev3_format_macros.tex, which
#    preamble.tex reads after every other macro file.
F = ["% AUTO-GENERATED by paper/arxiv_rev3/scripts/emit_rev3_macros.py: \\renewcommand of bare integers",
     "% of four or more digits with a thousands separator (value unchanged). Do not edit."]
for name, val in sorted(MAC.items()):
    m = re.fullmatch(r"(\$?)(-?)(\d{4,})(\$?)", val)
    if m and not (1990 <= int(m.group(3)) <= 2030 and not m.group(2)):
        new = m.group(1) + m.group(2) + f"{int(m.group(3)):,}".replace(",", "{,}") + m.group(4)
        assert new.replace("{,}", "") == val
        F.append(f"\\renewcommand{{\\{name}}}{{{new}}}")
# Sentence macros that print a token cap without a separator (1024, 2048).
for name, val in sorted(MAC.items()):
    if re.search(r"[A-Za-z]{3}", val) and re.search(r"(?<![\d{,.])(1024|2048)(?!\d)", val):
        new = re.sub(r"(?<![\d{,.])(1024|2048)(?!\d)", lambda m: m.group(1)[0] + "{,}" + m.group(1)[1:], val)
        assert new.replace("{,}", "") == val.replace("{,}", "")
        F.append(f"\\renewcommand{{\\{name}}}{{{new}}}")
# Audit N6: level accuracies of the MATH L4-5 run were rounded twice in hard_math_macros.tex (the JSON
# keeps two decimals). Re-round once from the unrounded values in tables/hard_math.json.
HMJ = json.load(open(os.path.join(REV3, "tables", "hard_math.json")))
KEYS = {"Sa": "SA", "Sctwo": "SC_k2", "Scfour": "SC_k4", "Sceight": "SC_k8", "Sctwelve": "SC_k12",
        "Deb": "DEBATE_N3_R1", "Ge": "GE_R2", "Hier": "HIER_M3", "Du": "DU"}
nfix = 0
for kn, cfg in KEYS.items():
    for L, Ln in (("4", "Lfour"), ("5", "Lfive")):
        v = HMJ["level"][L][cfg]
        once = f"{v:.1f}"
        old_v = MAC[f"HmAcc{kn}{Ln}"]
        assert abs(float(old_v) - v) < 0.1, (kn, L)  # at most a double-rounding step
        if once != old_v:
            F.append(f"\\renewcommand{{\\HmAcc{kn}{Ln}}}{{{once}}}")
            nfix += 1
assert nfix >= 1  # SC k=8 on level 5: 159/402 = 39.55... prints 39.6, not 39.5
assert any("HmAccSceightLfive}{39.6}" in x for x in F)
# Audit M2: the rev2 output-token sentence is about the original 60-item MATH run.
v = MAC["MathOutFrontierSentence"]
assert v.startswith("On MATH under output-only costing")
F.append("\\renewcommand{\\MathOutFrontierSentence}{" + v.replace("On MATH under", "On MATH$_{60}$ under", 1) + "}")
open(os.path.join(REV3, "rev3_format_macros.tex"), "w").write("\n".join(F) + "\n")
print("\n".join(F))
