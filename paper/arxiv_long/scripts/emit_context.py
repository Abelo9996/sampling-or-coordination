"""Context-window check (third-review revision, item G).

Ollama served every Qwen2.5-3B run with its default context window of 4,096
tokens (the M4 server's /api/ps reports context_length 4096 under Ollama
0.30.10, and its llama-server runs with -c 4096; the RTX 4060 service default is
the same). The cap-2048 check used a model alias with an 8,192-token context and
is not checked here.

For every log that records per-call token counts, this script finds the largest
prompt plus output of one call (in_tokens + out_tokens) and counts the calls
above 4,096. Logs without per-call counts (gsm8k_matrix, math500_trunc,
math500_trunc_sc24, mmlu_matrix, mmlu_pro_eng_matrix, gsm8k_scale200) cannot be
checked this way. results/power/math500hard* is not read (a committed protocol
forbids looking at that run before it ends). The MATH coordination trace
results/math500_qwen3b_coord_trace.jsonl was still being written when this ran;
its current maximum is reported in the JSON, and the paper's MATH figure is the
maximum over the held-out MATH traces and that file.

Writes tables/context.json and context_macros.tex. Usage:
python3 scripts/emit_context.py
"""

import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", "..", ".."))
RES = os.path.join(ROOT, "results")
CTX = 4096
GROUPS = {
    "Gsm": ["gsm8k_qwen3b_coord_trace.jsonl", "power/gsm8k_qwen3b_s1.jsonl",
            "power/gsm8k_qwen3b_s2.jsonl", "power/gsm8k_qwen3b_s3.jsonl"],
    "Math": ["math500_traces_mac.jsonl", "math500_traces_mac_b.jsonl",
             "math500_qwen3b_coord_trace.jsonl"],
    "Mmlu": ["mmlu_traces_mac.jsonl"],
    "Eng": ["mmlu_pro_eng_traces_mac.jsonl", "mmlu_pro_eng_traces_mac_b.jsonl"],
    "Code": ["humaneval_matrix_pc.jsonl"],
}


def scan(name):
    assert "math500hard" not in name
    best, n, over, recs_over = None, 0, [], set()
    for line in open(os.path.join(RES, name)):
        if not line.strip():
            continue
        r = json.loads(line)
        for i, c in enumerate(r["calls"]):
            s = c["in_tokens"] + c["out_tokens"]
            n += 1
            if best is None or s > best["total"]:
                best = {"total": s, "in": c["in_tokens"], "out": c["out_tokens"],
                        "config": r["config"], "item": r["item_id"], "call": i}
            if s > CTX:
                over.append({"config": r["config"], "item": r["item_id"], "call": i,
                             "in": c["in_tokens"], "out": c["out_tokens"]})
                recs_over.add((r["config"], r["item_id"], r.get("seed")))
    return {"calls": n, "max": best, "over": over, "records_over": len(recs_over)}


def comma(x):
    return f"{x:,}".replace(",", "{,}")


def main():
    out = {"ctx": CTX, "files": {}, "groups": {}}
    for g, files in GROUPS.items():
        res = {f: scan(f) for f in files}
        out["files"].update(res)
        mx = max((v["max"] for v in res.values()), key=lambda m: m["total"])
        out["groups"][g] = {"max": mx, "calls": sum(v["calls"] for v in res.values()),
                            "over": sum(len(v["over"]) for v in res.values()),
                            "records_over": sum(v["records_over"] for v in res.values())}
    json.dump(out, open(os.path.join(HERE, "..", "tables", "context.json"), "w"), indent=1)
    G = out["groups"]
    # the text says: no call above the window except in the MMLU-Pro eng. traces
    assert all(G[g]["over"] == 0 for g in ("Gsm", "Math", "Mmlu", "Code")), G
    M = ["% AUTO-GENERATED by paper/arxiv_long/scripts/emit_context.py. Do not edit.",
         f"\\newcommand{{\\CtxWindow}}{{{comma(CTX)}}}"]
    for g in GROUPS:
        M.append(f"\\newcommand{{\\CtxMax{g}}}{{{comma(G[g]['max']['total'])}}}")
    e = G["Eng"]
    M.append(f"\\newcommand{{\\CtxEngOver}}{{{e['over']}}}")
    M.append(f"\\newcommand{{\\CtxEngCalls}}{{{comma(e['calls'])}}}")
    M.append(f"\\newcommand{{\\CtxEngRecsOver}}{{{e['records_over']}}}")
    M.append(f"\\newcommand{{\\CtxEngMaxIn}}{{{comma(e['max']['in'])}}}")
    M.append(f"\\newcommand{{\\CtxEngMaxOut}}{{{comma(e['max']['out'])}}}")
    cfgs = sorted({o["config"] for v in out["files"].values() for o in v["over"]})
    assert cfgs == ["DEBATE_N3_R1"], cfgs
    M.append(f"% calls above the window: {[o for v in out['files'].values() for o in v['over']]}")
    M.append(f"% MATH trace still running: {out['files']['math500_qwen3b_coord_trace.jsonl']['max']}")
    open(os.path.join(HERE, "..", "context_macros.tex"), "w").write("\n".join(M) + "\n")


if __name__ == "__main__":
    main()
