"""Measured throughput per configuration and hardware, from logged latency.

Every record carries `latency_s` (the sum of its calls' wall-clock latencies;
the harness issues a query's calls sequentially, one request at a time) and
exact token counts. Per (log, configuration) we report
  s/query        = mean latency_s over records
  queries/hour   = 3600 / (s/query)          (one sequential stream)
  output tok/s   = sum(out_tokens) / sum(latency_s)
  total tok/s    = sum(in_tokens + out_tokens) / sum(latency_s)
Latency includes prompt processing, so output tok/s is an end-to-end rate, not
a pure decode rate. Hardware provenance (paper Section 4 and
paper/eaai/ENGINEERING_EXPERIMENT.md): Apple M4 (16 GB, Ollama 0.30.10) for
the GSM8K, MATH, and MMLU matrices; RTX 4060 (8 GB, Ollama 0.40.1, flash
attention, q8_0 KV cache, reached over an SSH tunnel) for the 200-item GSM8K
confirmation and MMLU-Pro engineering. No energy is measured here.

MATH uses the 640-cap matrix log (all seven configurations, both seeds at a
uniform rate). The 1024-cap log is not used for throughput: its second-seed
debate records run at 5.6 output tok/s against 27 for the first seed, which
indicates a machine shared with another job during that run.

Writes paper/eaai/throughput_macros.tex, paper/eaai/throughput_table.tex,
results/analysis/throughput.json.
"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RES = os.path.join(ROOT, "results")
OUT = os.path.join(ROOT, "paper", "eaai")

HEAD = ["SA", "SC_k2", "SC_k4", "SC_k8", "DEBATE_N3_R1", "GE_R2", "HIER_M3"]
LOGS = [  # (key, file, task label, hardware, cap, configs)
    ("gsmM", "gsm8k_matrix.jsonl", "GSM8K", "Apple M4", 640, HEAD),
    ("mathM", "math500_matrix.jsonl", "MATH", "Apple M4", 640, HEAD),
    ("mmluM", "mmlu_matrix.jsonl", "MMLU", "Apple M4", 640, HEAD),
    ("gsmG", "gsm8k_scale200.jsonl", "GSM8K ($n{=}200$)", "RTX 4060", 640,
     ["SA", "SC_k8", "DEBATE_N3_R1"]),
    ("engG", "mmlu_pro_eng_matrix.jsonl", "MMLU-Pro eng.", "RTX 4060", 1024, HEAD),
    ("codeG", "humaneval_matrix_pc.jsonl", "HumanEval", "RTX 4060", 1024, HEAD),
]
LABEL = {"SA": "SA", "SC_k2": "SC $k{=}2$", "SC_k4": "SC $k{=}4$",
         "SC_k8": "SC $k{=}8$", "DEBATE_N3_R1": "DEBATE", "GE_R2": "GE",
         "HIER_M3": "HIER"}
MAC = {"SA": "Sa", "SC_k2": "ScTwo", "SC_k4": "ScFour", "SC_k8": "ScEight",
       "DEBATE_N3_R1": "Deb", "GE_R2": "Ge", "HIER_M3": "Hier"}


def load(fname, items=None):
    rows = [json.loads(l) for l in open(os.path.join(RES, fname))]
    if items is not None:
        rows = [r for r in rows if r["item_id"] in items]
    return rows


def stats(rows):
    lat = sum(r["latency_s"] for r in rows)
    out = sum(r["out_tokens"] for r in rows)
    tot = sum(r["in_tokens"] + r["out_tokens"] for r in rows)
    calls = sum(r["n_calls"] for r in rows)
    spq = lat / len(rows)
    return {"n_records": len(rows), "calls_per_query": calls / len(rows),
            "s_per_query": spq, "queries_per_hour": 3600.0 / spq,
            "out_tok_s": out / lat, "total_tok_s": tot / lat,
            "s_per_call": lat / calls}


def main():
    res = {}
    for key, fname, task, hw, cap, cfgs in LOGS:
        rows = load(fname)
        res[key] = {"file": fname, "task": task, "hardware": hw, "cap": cap,
                    "configs": {c: stats([r for r in rows if r["config"] == c])
                                for c in cfgs}}
    # Matched comparison: GSM8K items shared by the M4 matrix (80) and the
    # 4060 confirmation (200, whose first 80 are the matrix items).
    m4 = load("gsm8k_matrix.jsonl")
    items = {r["item_id"] for r in m4}
    g = load("gsm8k_scale200.jsonl", items)
    matched = {}
    for c in ["SA", "SC_k8", "DEBATE_N3_R1"]:
        a = stats([r for r in m4 if r["config"] == c])
        b = stats([r for r in g if r["config"] == c])
        matched[c] = {"m4": a, "rtx4060": b,
                      "speedup_qph": b["queries_per_hour"] / a["queries_per_hour"],
                      "n_items": len({r["item_id"] for r in g if r["config"] == c})}
    res["matched_gsm8k"] = matched
    os.makedirs(os.path.join(RES, "analysis"), exist_ok=True)
    json.dump(res, open(os.path.join(RES, "analysis", "throughput.json"), "w"),
              indent=1)

    f = lambda x, d=0: f"{x:,.{d}f}".replace(",", "{,}")
    mac = ["% Generated by scripts/emit_throughput.py from results/*.jsonl latency_s."]
    for key in ["gsmM", "mathM", "mmluM", "gsmG", "engG", "codeG"]:
        for c, s in res[key]["configs"].items():
            nm = key + MAC[c]
            mac.append(rf"\newcommand{{\qph{nm}}}{{{f(s['queries_per_hour'])}}}")
            mac.append(rf"\newcommand{{\tps{nm}}}{{{f(s['out_tok_s'], 1)}}}")
    sp = [matched[c]["speedup_qph"] for c in matched]
    mac.append(rf"\newcommand{{\thrSpeedLo}}{{{min(sp):.1f}}}")
    mac.append(rf"\newcommand{{\thrSpeedHi}}{{{max(sp):.1f}}}")
    mac.append(rf"\newcommand{{\thrMatchedN}}{{{matched['SA']['n_items']}}}")
    open(os.path.join(OUT, "throughput_macros.tex"), "w").write("\n".join(mac) + "\n")

    t = [r"% Generated by scripts/emit_throughput.py; do not edit by hand.",
         r"\begin{table}[tp]\centering\scriptsize",
         r"\caption{Measured throughput per configuration and hardware, from the "
         r"logged per-query latency (one sequential request stream, the way the "
         r"harness ran). Queries/h $= 3600/\overline{\mathrm{latency}}$; output "
         r"tok/s is total output tokens over total latency, prompt processing "
         r"included; total tok/s counts input and output tokens. Apple~M4: Ollama 0.30.10; RTX~4060: Ollama 0.40.1 with flash "
         r"attention and an 8-bit key-value cache, reached over an SSH tunnel "
         r"(HumanEval: the harness ran on the PC itself, with sandboxed test "
         r"execution outside the timed calls). "
         r"GPU energy was measured only in the HumanEval run (main-text "
         r"Table~\ref{M-tab:code}).}",
         r"\label{tab:throughput}",
         r"\renewcommand{\arraystretch}{0.95}",
         r"\begin{tabular}{@{}lrrrrr@{}}", r"\toprule",
         r"Configuration & Calls/query & s/query & Queries/h & "
         r"Output tok/s & Total tok/s \\",
         r"\midrule"]
    for i, key in enumerate(["gsmM", "mathM", "mmluM", "gsmG", "engG", "codeG"]):
        L = res[key]
        if i:
            t.append(r"\addlinespace")
        t.append(rf"\multicolumn{{6}}{{@{{}}l}}{{\emph{{{L['hardware']}}}: "
                 rf"{L['task']}, {L['cap']}-token cap}} \\")
        for c, s in L["configs"].items():
            t.append(rf"\quad {LABEL[c]} & {s['calls_per_query']:.1f} & "
                     rf"{f(s['s_per_query'], 1)} & {f(s['queries_per_hour'])} & "
                     rf"{s['out_tok_s']:.1f} & {s['total_tok_s']:.1f} \\")
    t += [r"\bottomrule", r"\end{tabular}", r"\end{table}"]
    open(os.path.join(OUT, "throughput_table.tex"), "w").write("\n".join(t) + "\n")
    for key in res:
        if key == "matched_gsm8k":
            continue
        print(key, {c: (round(s["queries_per_hour"]), round(s["out_tok_s"], 1))
                    for c, s in res[key]["configs"].items()})
    print("matched speedups", {c: round(matched[c]["speedup_qph"], 2) for c in matched})


if __name__ == "__main__":
    main()
