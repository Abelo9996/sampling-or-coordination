"""Evidence column of the deployment-guideline table (Table 7), from the logs.

For each guideline row, the supporting paired comparison(s): task, number of
items, accuracy difference in points with a 95% interval from the seed-aware
hierarchical bootstrap of harness/stats.py (10,000 resamples, seed 0; with one
seed per item it reduces to the item bootstrap), its two-sided p, and a status:
  Holm         Holm-adjusted p < 0.05 within the paper's per-task family
               (SC k=8 against DEBATE, GE, HIER), i.e. the paper's
               confirmatory tests;
  sig.         p < 0.05 for a comparison outside a Holm family;
  dir.         directional: interval includes 0, or a descriptive measurement.
  python3 scripts/emit_evidence.py --from-json   re-emits the macros from
  results/analysis/evidence.json without recomputing the bootstrap.
Writes paper/eaai/evidence_macros.tex and results/analysis/evidence.json.
Each value is also printed so it can be checked against the hand-typed numbers
of Sections 6 and S1 to S6.
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from harness import stats as S  # noqa: E402

B = 10000


def rows(fname):
    return [json.loads(l) for l in open(os.path.join(ROOT, "results", fname)) if l.strip()]


def cor_of(*fnames):
    out = {}
    for f in fnames:
        for c, m in S.per_item_seed_correct(rows(f)).items():
            out.setdefault(c, {}).update(m)
    return out


def comp(cor, a, b):
    d, p, lo, hi = S.hier_paired_test(cor[a], cor[b], B=B, seed=0)
    n = len(set(cor[a]) & set(cor[b]))
    return {"a": a, "b": b, "n": n, "delta": d, "lo": lo, "hi": hi, "p": p}


def main():
    if "--from-json" in sys.argv:
        ev = json.load(open(os.path.join(ROOT, "results", "analysis", "evidence.json")))
        return write(ev)
    ev = {}
    # Holm families: SC k=8 vs the three headline coordination workflows
    fam = {}
    for task in ("gsm8k", "math500", "mmlu", "mmlu_pro_eng"):
        h = S.headline_hier(task, B=B, seed=0)
        fam[task] = h
        for c, r in h.items():
            ev[f"{task}:SC_k8-{c}"] = {"a": "SC_k8", "b": c, "delta": r["delta"],
                                       "lo": r["ci"][0], "hi": r["ci"][1], "p": r["p"],
                                       "holm": r["holm"]}
    nmap = {"gsm8k": "gsm8k_matrix.jsonl", "math500": "math500_trunc.jsonl",
            "mmlu": "mmlu_matrix.jsonl", "mmlu_pro_eng": "mmlu_pro_eng_matrix.jsonl"}
    for task, f in nmap.items():
        cor = cor_of(f)
        for k in list(ev):
            if k.startswith(task + ":"):
                ev[k]["n"] = len(set(cor["SC_k8"]) & set(cor[ev[k]["b"]]))
        ev[f"{task}:SC_k8-SA"] = comp(cor, "SC_k8", "SA")
    cor = cor_of("gsm8k_matrix.jsonl")
    ev["gsm8k:SC_k12-SC_k8"] = comp(cor, "SC_k12", "SC_k8")
    # diversity probes (same 80 GSM8K items, two seeds)
    cor = cor_of("gsm8k_matrix.jsonl", "gsm8k_debate_div.jsonl", "gsm8k_debate_hetero.jsonl")
    divc = [c for c in cor if c.startswith("DEBATED")][0]
    hetc = [c for c in cor if c.startswith("DEBATEH")][0]
    ev["div:SC_k8-DEBATED"] = comp(cor, "SC_k8", divc)
    ev["div:SC_k8-DEBATEH"] = comp(cor, "SC_k8", hetc)
    ev["div:DEBATED-DEBATE"] = comp(cor, divc, "DEBATE_N3_R1")
    ev["div:DEBATEH-DEBATE"] = comp(cor, hetc, "DEBATE_N3_R1")
    # cross-family probe (n=50, one seed)
    for fam_name, f in (("llama", "gsm8k_llama3b.jsonl"), ("gemma", "gsm8k_gemma2b.jsonl")):
        cor = cor_of(f)
        for c in ("DEBATE_N3_R1", "GE_R2", "HIER_M3"):
            ev[f"{fam_name}:SC_k8-{c}"] = comp(cor, "SC_k8", c)
    for k, v in ev.items():
        v["status"] = ("Holm" if v.get("holm", 1) < 0.05 else
                       "sig." if ("holm" not in v and v["p"] < 0.05) else "dir.")
    write(ev)


def write(ev):

    for v in ev.values():
        v["status"] = "dir." if v["status"] == "directional" else v["status"]
    os.makedirs(os.path.join(ROOT, "results", "analysis"), exist_ok=True)
    json.dump(ev, open(os.path.join(ROOT, "results", "analysis", "evidence.json"), "w"),
              indent=1)
    name = lambda k: "ev" + "".join(
        {"gsm8k": "Gsm", "math500": "Math", "mmlu": "Mmlu", "mmlu_pro_eng": "Eng",
         "div": "Div", "llama": "Llama", "gemma": "Gemma"}[k.split(":")[0]] +
        k.split(":")[1].replace("SC_k8", "Sc").replace("SC_k12", "Sctw").replace("SA", "Sa")
        .replace("DEBATE_N3_R1", "Deb").replace("DEBATED", "Div").replace("DEBATEH", "Het")
        .replace("DEBATE", "Deb").replace("GE_R2", "Ge").replace("HIER_M3", "Hier")
        .replace("-", "").replace("_", "") for _ in [0])
    f2 = lambda x: "{" + (f"{x:+.1f}" if abs(x) >= 0.05 else "0.0") + "}"
    L = ["% Generated by scripts/emit_evidence.py from the logs; do not edit by hand."]
    for k, v in ev.items():
        nm = name(k)
        L.append(rf"\newcommand{{\{nm}}}{{{f2(v['delta'])}}}")
        L.append(rf"\newcommand{{\{nm}Lo}}{{{f2(v['lo'])}}}")
        L.append(rf"\newcommand{{\{nm}Hi}}{{{f2(v['hi'])}}}")
        L.append(rf"\newcommand{{\{nm}N}}{{{v['n']}}}")
        L.append(rf"\newcommand{{\{nm}St}}{{{v['status']}}}")
        print(f"{k:28} {nm:18} n={v['n']:3} d={v['delta']:+6.1f} "
              f"[{v['lo']:+6.1f},{v['hi']:+6.1f}] p={v['p']:.4f} "
              f"holm={v.get('holm', float('nan')):.4f} {v['status']}")
    open(os.path.join(ROOT, "paper", "eaai", "evidence_macros.tex"), "w").write("\n".join(L) + "\n")


if __name__ == "__main__":
    main()
