"""Emit paper/aaibd/rerun_macros.tex: the cells of the AAIBD revision that depend
on reruns still in progress. No model calls; reads logs only.

1. MATH (levels 1-3, 1024-token cap) SC k=2 and k=4, from
   results/math500_trunc_sc24.jsonl (written by scripts/run_aaibd_rerun.py).
   A config is used only when it is complete: the 60 items of the SA records of
   results/math500_trunc.jsonl x seeds {1, 2}. Otherwise its cells print
   "pending".
2. Cross-family GSM8K probe (Llama-3.2-3B, Gemma-2-2B, n=50). Seed 1 is
   results/gsm8k_{llama3b,gemma2b}.jsonl; seed 2 is
   results/gsm8k_{llama3b,gemma2b}_seed2.jsonl (six stochastic configs; the
   greedy SA has one seed). When the seed-2 file of a family is complete, that
   family's cells are two-seed means; otherwise the seed-1 numbers are printed.

Aggregation is the paper's (harness/analyze.py): average correctness and cost
over seeds within an item, then the item mean; 95% CI = item bootstrap
percentile interval (analyze._bootstrap_ci with B=10,000, numpy seed 0, as in
scripts/aaibd_revision_stats.py section E).

The MATH output-token frontier sentence and the MATH rerun comparison sentence
are also emitted here, so the paper text updates with the rerun. Comparisons
use harness/stats.hier_paired_test (items, then seeds within item; 10,000
replicates, seed 0), the paper's primary test.

  python3 scripts/aaibd_emit_rerun_macros.py
"""
import json
import os
import sys
from collections import defaultdict

import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from harness import analyze, stats  # noqa: E402

RES = os.path.join(ROOT, "results")
OUT = os.path.join(ROOT, "paper", "aaibd", "rerun_macros.tex")

MATH_REF = os.path.join(RES, "math500_trunc.jsonl")
MATH_SC24 = os.path.join(RES, "math500_trunc_sc24.jsonl")
XF = [("Llama", "gsm8k_llama3b.jsonl", "gsm8k_llama3b_seed2.jsonl"),
      ("Gemma", "gsm8k_gemma2b.jsonl", "gsm8k_gemma2b_seed2.jsonl")]
XF_CFGS = ["SA", "SC_k2", "SC_k4", "SC_k8", "DEBATE_N3_R1", "GE_R2", "HIER_M3"]
STOCH = XF_CFGS[1:]
COORD = ["DEBATE_N3_R1", "GE_R2", "HIER_M3"]
NAME = {"SA": "Sa", "SC_k2": "Sctwo", "SC_k4": "Scfour", "SC_k8": "Sceight",
        "SC_k12": "Sctwelve", "DEBATE_N3_R1": "Deb", "GE_R2": "Ge",
        "HIER_M3": "Hier"}
TEXLAB = {"SA": "the single call", "SC_k2": "SC $k{=}2$", "SC_k4": "SC $k{=}4$",
          "SC_k8": "SC $k{=}8$", "SC_k12": "SC $k{=}12$",
          "DEBATE_N3_R1": "debate", "GE_R2": "GE", "HIER_M3": "HIER"}


def read(path):
    if not os.path.exists(path):
        return []
    with open(path) as f:
        return [json.loads(l) for l in f if l.strip()]


def cell(rows, cfg):
    """Seed-average within item, item mean, item-bootstrap CI."""
    by = defaultdict(list)
    for r in rows:
        if r["config"] == cfg:
            by[r["item_id"]].append(r)
    corr = np.array([np.mean([int(r["correct"]) for r in v]) for v in by.values()])
    tot = np.array([np.mean([r["total_tokens"] for r in v]) for v in by.values()])
    out = np.array([np.mean([r["out_tokens"] for r in v]) for v in by.values()])
    lo, hi = analyze._bootstrap_ci(corr, B=10000)
    n_rec = sum(len(v) for v in by.values())
    pf = sum(1 for v in by.values() for r in v if r.get("pred") is None)
    return {"acc": 100 * corr.mean(), "lo": 100 * lo, "hi": 100 * hi,
            "tok": tot.mean(), "out": out.mean(), "n_items": len(by),
            "n_rec": n_rec, "pf_pct": 100.0 * pf / n_rec if n_rec else float("nan")}


def complete(rows, cfg, items, seeds):
    have = {(r["item_id"], r["seed"]) for r in rows if r["config"] == cfg}
    return all((i, s) in have for i in items for s in seeds), len(have)


def mac(name, val):
    return f"\\newcommand{{\\{name}}}{{{val}}}"


def fmt_tok(x):
    return f"{x:,.0f}".replace(",", "{,}")


def frontier(points):
    """points: {cfg: (cost, acc)} -> non-dominated cfgs (point estimates)."""
    front = []
    for c, (x, y) in points.items():
        dom = any(xx <= x and yy >= y and (xx < x or yy > y)
                  for cc, (xx, yy) in points.items() if cc != c)
        if not dom:
            front.append(c)
    return sorted(front, key=lambda c: points[c][0])


def seed_maps(rows, cfg):
    c = defaultdict(list)
    t = defaultdict(list)
    for r in rows:
        if r["config"] == cfg:
            c[r["item_id"]].append(int(r["correct"]))
            t[r["item_id"]].append(r["total_tokens"])
    return ({i: np.asarray(v, float) for i, v in c.items()},
            {i: float(np.mean(v)) for i, v in t.items()})


def main():
    L = ["% AUTO-GENERATED by scripts/aaibd_emit_rerun_macros.py. Do not edit.",
         "% Regenerate after the reruns land: python3 scripts/aaibd_emit_rerun_macros.py"]

    # MATH SC k=2, k=4 at the 1024 cap
    ref = read(MATH_REF)
    items = sorted({r["item_id"] for r in ref if r["config"] == "SA"})
    sc24 = read(MATH_SC24)
    done = {}
    for cfg in ["SC_k2", "SC_k4"]:
        ok, nhave = complete(sc24, cfg, items, [1, 2])
        n = NAME[cfg]
        L.append(f"% MATH {cfg} @1024: {'complete' if ok else 'PENDING'} "
                 f"({nhave}/{2 * len(items)} item-seed records)")
        if ok:
            c = cell(sc24, cfg)
            done[cfg] = c
            L += [mac(f"Math{n}Acc", f"{c['acc']:.1f}"),
                  mac(f"Math{n}CI", f"[{c['lo']:.0f},{c['hi']:.0f}]"),
                  mac(f"Math{n}Tok", f"{c['tok']:.0f}"),
                  mac(f"Math{n}Out", f"{c['out']:.0f}")]
        else:
            L += [mac(f"Math{n}Acc", "pending"), mac(f"Math{n}CI", ""),
                  mac(f"Math{n}Tok", "pending"), mac(f"Math{n}Out", "pending")]
    state = "complete" if len(done) == 2 else "pending"
    L.append(mac("MathRerunState", state))

    # output-token frontier on MATH at 1024 (point estimates)
    allrows = ref + [r for r in sc24 if r["config"] in done]
    cfgs = sorted({r["config"] for r in allrows})
    cells = {c: cell(allrows, c) for c in cfgs}
    pts = {c: (cells[c]["out"], cells[c]["acc"]) for c in cfgs}
    fr = frontier(pts)
    deb = cells["DEBATE_N3_R1"]
    L.append(f"% MATH 1024 output-token frontier over {cfgs}: {fr}")
    if "DEBATE_N3_R1" in fr:
        dominators = []
        s = (f"On MATH under output-only costing, debate ({fmt_tok(deb['out'])} "
             f"output tokens, {deb['acc']:.1f}\\%) is on the point-estimate frontier, "
             f"because SC $k{{=}}8$ generates more ({fmt_tok(cells['SC_k8']['out'])})")
        if state == "pending":
            s += ("; SC $k{=}2$ and $k{=}4$ at the 1024 cap, which could change this, "
                  "are being rerun")
        else:
            s += (" and neither SC $k{=}2$ nor SC $k{=}4$ at the 1024 cap is both "
                  "lower in output tokens and at least as accurate")
        s += "."
    else:
        dominators = [c for c in cfgs if c != "DEBATE_N3_R1"
                      and pts[c][0] <= pts["DEBATE_N3_R1"][0]
                      and pts[c][1] >= pts["DEBATE_N3_R1"][1]]
        parts = [f"{TEXLAB[c]} ({fmt_tok(cells[c]['out'])} output tokens, "
                 f"{cells[c]['acc']:.1f}\\%)" for c in dominators]
        s = (f"On MATH under output-only costing, debate ({fmt_tok(deb['out'])} "
             f"output tokens, {deb['acc']:.1f}\\%) is off the point-estimate frontier: "
             + " and ".join(parts) + (" uses" if len(parts) == 1 else " use")
             + " fewer output tokens at equal or higher point accuracy.")
    L.append(mac("MathOutFrontierSentence", s))

    # MATH rerun comparisons vs coordination (hierarchical bootstrap)
    if state == "pending":
        cmp = ("SC $k{=}2$ and $k{=}4$ at the 1024 cap are being rerun, so the "
               "MATH rows use SA, SC $k{=}8$ and SC $k{=}12$ as comparators.")
    else:
        bits, recs = [], []
        for sc in ["SC_k2", "SC_k4"]:
            a_c, a_t = seed_maps(allrows, sc)
            for co in COORD:
                b_c, b_t = seed_maps(allrows, co)
                d, p, lo, hi = stats.hier_paired_test(a_c, b_c)
                dt = np.mean([a_t[i] - b_t[i] for i in sorted(set(a_t) & set(b_t))])
                if dt < 0:
                    code = "R" if lo > 0 else ("C" if hi >= 0 else "N")
                    v = {"R": "robustly dominates",
                         "C": "is cheaper, accuracy not distinguishable from",
                         "N": "is cheaper but less accurate than"}[code]
                    recs.append((sc, co, d, lo, hi, dt, code))
                    bits.append(f"{TEXLAB[sc]} {v} {TEXLAB[co]} "
                                f"(${d:+.1f}$, $[{lo:+.1f},{hi:+.1f}]$, "
                                f"${dt:+.0f}$ tokens)")
        if len(recs) == 6 and all(r[6] == "C" for r in recs):
            # compact form: every pairing has the same verdict
            mn = min(recs, key=lambda r: r[2])
            mx = max(recs, key=lambda r: r[2])
            cmp = ("SC $k{=}2$ and $k{=}4$ at the 1024 cap are each cheaper than "
                   "debate, GE and HIER in total tokens, with accuracy not "
                   "distinguishable in any of the six pairings (hierarchical "
                   f"bootstrap; from {TEXLAB[mn[0]]} minus {TEXLAB[mn[1]]}, "
                   f"${mn[2]:+.1f}$, $[{mn[3]:+.1f},{mn[4]:+.1f}]$, to "
                   f"{TEXLAB[mx[0]]} minus {TEXLAB[mx[1]]}, ${mx[2]:+.1f}$, "
                   f"$[{mx[3]:+.1f},{mx[4]:+.1f}]$).")
        else:
            cmp = ("With SC $k{=}2$ and $k{=}4$ at the 1024 cap included "
                   "(hierarchical bootstrap): " + ("; ".join(bits) if bits else
                   "neither is cheaper than any coordination workflow") + ".")
    L.append(mac("MathRerunCompareSentence", cmp))

    # cross-family GSM8K probe
    # Preferred set (same runtime session, November 2026): greedy SA from
    # *_driftcheck.jsonl, seed 1 from *_seed1_rerun.jsonl, seed 2 from
    # *_seed2.jsonl. The July single-seed file is reported only as a disclosed
    # earlier replicate (XfJul* macros), because a greedy rerun no longer
    # reproduces it for Llama and Gemma. Fallback if the November set is
    # incomplete: July seed 1 (+ seed 2 if complete), as before.
    xf_two, xf_nov = [], []
    for fam, f1, f2 in XF:
        stem = f1[:-len(".jsonl")]
        r1 = read(os.path.join(RES, f1))
        r2 = read(os.path.join(RES, f2))
        dc = [r for r in read(os.path.join(RES, stem + "_driftcheck.jsonl"))
              if r["config"] == "SA"]
        s1 = read(os.path.join(RES, stem + "_seed1_rerun.jsonl"))
        fitems = sorted({r["item_id"] for r in r1 if r["config"] == "SA"})
        ok2 = all(complete(r2, c, fitems, [2])[0] for c in STOCH) if r2 else False
        ok1 = all(complete(s1, c, fitems, [1])[0] for c in STOCH) if s1 else False
        okd = sorted({r["item_id"] for r in dc}) == fitems
        nov = ok1 and ok2 and okd
        if nov:
            rows = dc + s1 + r2
            xf_nov.append(fam)
        else:
            rows = r1 + (r2 if ok2 else [])
        L.append(f"% {fam}: " + ("November same-runtime set (driftcheck SA + seed1_rerun + seed2)"
                 if nov else f"seed-2 file {f2} "
                 f"{'complete, two-seed means' if ok2 else 'absent or incomplete, seed 1 only'}"))
        if ok2:
            xf_two.append(fam)
        cs = {}
        for c in XF_CFGS:
            cs[c] = cell(rows, c)
            n = NAME[c]
            L += [mac(f"Xf{fam}{n}Acc", f"{cs[c]['acc']:.1f}"),
                  mac(f"Xf{fam}{n}CI", f"[{cs[c]['lo']:.0f},{cs[c]['hi']:.0f}]"),
                  mac(f"Xf{fam}{n}Tok", f"{cs[c]['tok']:.0f}"),
                  mac(f"Xf{fam}{n}Pf", f"{cs[c]['pf_pct']:.0f}")]
        bestc = max(COORD, key=lambda c: cs[c]["acc"])
        best = cs[bestc]["acc"]
        L.append(mac(f"Xf{fam}Delta", f"{cs['SC_k8']['acc'] - best:+.1f}"))
        pfmax = max(cs[c]["pf_pct"] for c in XF_CFGS)
        L.append(mac(f"Xf{fam}PfMax", f"{pfmax:.0f}"))
        if nov:
            # hierarchical paired tests on the November set
            def ht(a, b):
                d, p, lo, hi = stats.hier_paired_test(seed_maps(rows, a)[0],
                                                      seed_maps(rows, b)[0])
                return d, p, lo, hi
            def ci(t):
                return f"${t[0]:+.1f}$, $[{t[2]:+.1f},{t[3]:+.1f}]$"
            L.append(mac(f"Xf{fam}BestCoord", TEXLAB[bestc]))
            L.append(mac(f"Xf{fam}ScVsBest", ci(ht("SC_k8", bestc))))
            L.append(mac(f"Xf{fam}ScVsSa", ci(ht("SC_k8", "SA"))))
            L.append(mac(f"Xf{fam}SaVsBest", ci(ht("SA", bestc))))
            for c in COORD:
                L.append(mac(f"Xf{fam}SaVs{NAME[c]}", ci(ht("SA", c))))
                t = ht("SC_k8", c)
                L.append(mac(f"Xf{fam}ScVs{NAME[c]}", ci(t)))
            # July single-seed replicate and greedy drift, for disclosure
            jul = {c: cell(r1, c) for c in XF_CFGS}
            for c in XF_CFGS:
                L.append(mac(f"XfJul{fam}{NAME[c]}Acc", f"{jul[c]['acc']:.0f}"))
            jsa = {r["item_id"]: r for r in r1 if r["config"] == "SA"}
            dsa = {r["item_id"]: r for r in dc}
            same = sum(1 for i in fitems if str(jsa[i]["pred"]) == str(dsa[i]["pred"]))
            L.append(mac(f"XfDrift{fam}Match", f"{same}"))
            L.append(mac(f"XfDrift{fam}JulCorrect", f"{sum(int(jsa[i]['correct']) for i in fitems)}"))
            L.append(mac(f"XfDrift{fam}NovCorrect", f"{sum(int(dsa[i]['correct']) for i in fitems)}"))
    if len(xf_nov) == 2:
        note = ("November 2026 rerun in one runtime session: greedy SA (one seed) "
                "and two-seed means for every stochastic configuration")
    elif len(xf_two) == 2:
        note = ("Two-seed means (seeds 1 and 2; the greedy SA has one seed)")
    elif xf_two:
        note = (f"{' and '.join(xf_two)}: two-seed means (greedy SA one seed); "
                "other family: one seed (seed 1), second seed pending")
    else:
        note = "One seed (seed 1); a second-seed rerun is pending"
    L.append(mac("XfSeedNote", note))
    L.append(mac("XfState", "nov" if len(xf_nov) == 2 else "july"))

    with open(OUT, "w") as f:
        f.write("\n".join(L) + "\n")
    print("wrote", OUT, "| MATH SC2/4:", state, "| cross-family two-seed:", xf_two, "| november set:", xf_nov)


if __name__ == "__main__":
    main()
