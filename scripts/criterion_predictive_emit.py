"""Macros and table fragments for the criterion validation (called by
scripts/criterion_predictive.py; no hand-typed numbers in the paper).

Writes paper/eaai/criterion_predictive_macros.tex (prefix \\cp...),
paper/eaai/criterion_predictive_table.tex (main text, tab:predictive: per-cell
results of the base-accuracy screen, post hoc intervals),
paper/eaai/criterion_splits_table.tex (supplement, tab:S-splits: the
protocol's pilot-split results per cell), and
paper/eaai/criterion_pooled_table.tex (supplement, tab:pooled).
"""
import math
import os

ROMAN = {"R1": "Rone", "R2": "Rtwo", "R3_a_only": "Rthree", "always": "Always",
         "never": "Never", "ZERO": "Zero", "POOLD": "Poold"}
CELLMAC = {"gsm8k_qwen_debate": "GsmDeb", "gsm8k_qwen_ge": "GsmGe",
           "gsm8k_llama70b_debate": "SevDeb", "math_qwen_debate": "MathDeb",
           "math_qwen_ge": "MathGe", "mmlu_qwen_debate": "MmluDeb",
           "mmlu_qwen_ge": "MmluGe", "eng_qwen_debate": "EngDeb",
           "eng_qwen_ge": "EngGe"}
WFNAME = {"debate": "DEBATE", "ge": "GE"}


def pct(x, d=1):
    return f"{100 * x:.{d}f}"


def sgn(x, d=1):
    """Signed points in braces so a leading minus stays unary in math mode."""
    v = 100 * x
    s = f"{v:+.{d}f}"
    if s in ("+0.0", "-0.0"):
        s = "0.0"
    return "{" + s.replace("-", "-") + "}"


def pp(x, d=1):
    """Signed points for table cells; zero without a sign."""
    s = f"{100 * x:+.{d}f}"
    return "0.0" if s in ("+0.0", "-0.0") else s


def num(x, d=2):
    if x is None or (isinstance(x, float) and (math.isnan(x) or math.isinf(x))):
        return r"\infty" if x == float("inf") else "n/a"
    return f"{x:.{d}f}"


def emit(res, outdir):
    m = res["main"]
    L = ["% Generated by scripts/criterion_predictive.py from the trace logs;",
         "% protocol paper/eaai/CRITERION_PREDICTIVE.md. Do not edit by hand."]
    mac = lambda k, v: L.append(rf"\newcommand{{\cp{k}}}{{{v}}}")
    mac("M", res["m"])
    mac("Nsplits", res["n_splits"])
    mac("Ncells", len(m["cells"]))
    mac("Nitems", sum(c["n"] for c in res["cells"].values()))
    for k in ["R1", "R2", "R3_a_only", "always", "never"]:
        if f"acc_{k}" in m:
            mac("Acc" + ROMAN[k], pct(m[f"acc_{k}"]))
            mac("AccFull" + ROMAN[k], pct(m[f"acc_full_{k}"]))
    mac("AccBestConst", pct(m["best_constant"]))
    for k in ["R1", "R2", "ZERO", "POOLD"]:
        if f"mae_{k}" in m:
            mac("Mae" + ROMAN[k], pct(m[f"mae_{k}"]))
    for k in ["R1", "R2"]:
        c = m.get(f"corr_{k}")
        if c:
            mac("Corr" + ROMAN[k], "{" + f"{c['median']:.2f}" + "}")
            mac("Corr" + ROMAN[k] + "Lo", "{" + f"{c['lo']:.2f}" + "}")
            mac("Corr" + ROMAN[k] + "Hi", "{" + f"{c['hi']:.2f}" + "}")
            if c["r_splitavg_vs_full"] is not None:
                mac("Corr" + ROMAN[k] + "Avg", "{" + f"{c['r_splitavg_vs_full']:.2f}" + "}")
    mac("AllSameSign", "yes" if m["all_same_sign"] else "no")
    nneg = sum(1 for v in m["full_delta"].values() if v < 0)
    nzero = sum(1 for v in m["full_delta"].values() if v == 0)
    npos = sum(1 for v in m["full_delta"].values() if v > 0)
    mac("Nneg", nneg); mac("Nzero", nzero); mac("Npos", npos)
    hi = [c for c in res["cells"].values() if c["a"] > 0.5]
    lo = [c for c in res["cells"].values() if c["a"] < 0.5]
    mac("NhighA", len(hi)); mac("NhighANeg", sum(1 for c in hi if c["delta"] < 0))
    mac("NlowA", len(lo)); mac("NlowAPos", sum(1 for c in lo if c["delta"] > 0))
    mac("MinA", pct(min(c["a"] for c in res["cells"].values())))
    mac("MaxA", pct(max(c["a"] for c in res["cells"].values())))
    if "main_new_cells" in res:
        mn = res["main_new_cells"]
        for k in ["R1", "R2", "always", "never"]:
            if f"acc_{k}" in mn:
                mac("NewAcc" + ROMAN[k], pct(mn[f"acc_{k}"]))
        for k in ["R1", "R2", "ZERO", "POOLD"]:
            if f"mae_{k}" in mn:
                mac("NewMae" + ROMAN[k], pct(mn[f"mae_{k}"]))
    for cid, c in res["cells"].items():
        t = CELLMAC[cid]
        mac(t + "A", pct(c["a"]))
        mac(t + "Delta", sgn(c["delta"]))
        mac(t + "Fix", c["fix"]); mac(t + "Wrong", c["n_wrong"])
        mac(t + "Cor", c["cor"]); mac(t + "Right", c["n_right"])
    for name, P in res["pooled"].items():
        t = {"debate": "PoolDeb", "ge": "PoolGe", "all": "PoolAll",
             "new_cells": "PoolNew"}[name]
        mac(t + "N", P["n"])
        mac(t + "A", pct(P["a"]))
        mac(t + "Pfix", num(P["p_fix"])); mac(t + "Pcor", num(P["p_cor"]))
        mac(t + "Ratio", num(P["ratio"])); mac(t + "Odds", num(P["odds"]))
        mac(t + "RatioLo", num(P["ratio_ci"][0])); mac(t + "RatioHi", num(P["ratio_ci"][1]))
        mac(t + "OddsLo", num(P["odds_ci"][0])); mac(t + "OddsHi", num(P["odds_ci"][1]))
        mac(t + "Delta", sgn(P["delta"]))
        mac(t + "DeltaLo", sgn(P["delta_ci"][0])); mac(t + "DeltaHi", sgn(P["delta_ci"][1]))
        mac(t + "RatioBootLo", num(P["ratio_ci_boot"][0]))
        mac(t + "RatioBootHi", num(P["ratio_ci_boot"][1]))
    for mm, s in res["sensitivity_m"].items():
        w = {"10": "Ten", "20": "Twenty", "30": "Thirty", "40": "Forty"}[mm]
        mac("SensAccRone" + w, pct(s["acc_R1"]))
        mac("SensMaeRone" + w, pct(s["mae_R1"]))
        if "acc_R2" in s:
            mac("SensAccRtwo" + w, pct(s["acc_R2"]))
            mac("SensMaeRtwo" + w, pct(s["mae_R2"]))
    for cid, v in res.get("sanity_matrix_agreement", {}).items():
        t = CELLMAC[cid]
        mac(t + "Agree", pct(v["agree_final_seed1"], 0))
        mac(t + "TrInit", pct(v["trace_init_acc"]))
        mac(t + "TrFinal", pct(v["trace_final_acc"]))
        mac(t + "MxSone", pct(v["matrix_acc_seed1"]))
        mac(t + "MxStwo", pct(v["matrix_acc_seed2"]))
    # post hoc per-cell screen results (scripts/criterion_predictive.py,
    # posthoc_screen; added in answer to a review, labeled post hoc)
    ph = res["posthoc_screen"]
    for cid, v in ph["cells"].items():
        t = CELLMAC[cid]
        mac(t + "DeltaLo", sgn(v["delta_ci"][0])); mac(t + "DeltaHi", sgn(v["delta_ci"][1]))
        mac(t + "McP", f"{v['mcnemar_p']:.2f}")
    mac("ScreenRight", ph["n_right"])
    # the gap in base accuracy that no cell occupies: the data can place the
    # screen's threshold only somewhere inside it
    a_lo = max(c["a"] for c in res["cells"].values() if c["a"] < 0.5)
    a_hi = min(c["a"] for c in res["cells"].values() if c["a"] > 0.5)
    mac("GapLo", f"{a_lo:.2f}"); mac("GapHi", f"{a_hi:.2f}")
    mac("GapLoExact", f"{a_lo:.3f}"); mac("GapHiExact", f"{a_hi:.3f}")
    mac("ScreenNciExcl", ph["n_ci_excl_0"])
    for name, t in (("high_a", "HighA"), ("low_a", "LowA"), ("high_a_blind", "HighABlind")):
        g = ph["groups"].get(name)
        if not g:
            continue
        mac(t + "Cells", len(g["cells"])); mac(t + "N", g["n"])
        mac(t + "Delta", sgn(g["delta"]))
        mac(t + "DeltaLo", sgn(g["delta_ci"][0])); mac(t + "DeltaHi", sgn(g["delta_ci"][1]))
    # run-to-run reference on the engineering cells: final accuracy of the same
    # workflow in the M4 trace run and the two RTX 4060 matrix seeds
    for cid, v in res.get("sanity_matrix_agreement", {}).items():
        vals = [v["trace_final_acc"], v["matrix_acc_seed1"], v["matrix_acc_seed2"]]
        mac(CELLMAC[cid] + "RunSpread", pct(max(vals) - min(vals)))
    with open(os.path.join(outdir, "criterion_predictive_macros.tex"), "w") as f:
        f.write("\n".join(L) + "\n")

    # ---- support cell of the guideline-table row on proposed coordination steps
    gh, gl = ph["groups"]["high_a"], ph["groups"]["low_a"]
    G = [r"% Generated by scripts/criterion_predictive.py; do not edit by hand.",
         rf"Net change of the step, pooled: $a>\tfrac12$ ({len(gh['cells'])} cells, "
         rf"{gh['n']} item traces) ${100*gh['delta']:+.1f}$ "
         rf"[${100*gh['delta_ci'][0]:+.1f}$, ${100*gh['delta_ci'][1]:+.1f}$]; "
         rf"$a<\tfrac12$ ({len(gl['cells'])} cells, {gl['n']}) ${100*gl['delta']:+.1f}$ "
         rf"[${100*gl['delta_ci'][0]:+.1f}$, ${100*gl['delta_ci'][1]:+.1f}$]; "
         rf"\emph{{post hoc}}%"]
    with open(os.path.join(outdir, "guideline_criterion_cell.tex"), "w") as f:
        f.write("\n".join(G) + "\n")

    def cellname(c):
        return (f"{c['task'].replace('MMLU-Pro eng.', 'Eng.')} "
                f"{c['model'].replace('Qwen2.5-3B', '3B').replace('Llama-3.3-70B', '70B')} "
                f"{WFNAME[c['wf']]}")

    # ---- main-text table: per-cell results of the base-accuracy screen
    sm = res.get("sanity_matrix_agreement", {})
    T = [r"% Generated by scripts/criterion_predictive.py; do not edit by hand.",
         r"\begin{table}[t]\centering\scriptsize",
         r"\caption{Per-cell results of the base-accuracy screen (adopt a "
         r"coordination step only if $a<\tfrac12$), on the " + str(len(res["cells"])) +
         r" cells of the out-of-sample test (cells, traces, and rule fixed before the "
         r"runs). Per cell: base accuracy $a$; fixed of initially wrong and corrupted "
         r"of initially correct items; the observed net change $\Delta$ of the step on "
         r"all items, with a 95\% item-bootstrap interval (" +
         f"{10000:,}".replace(",", "{,}") + r" resamples) and the exact McNemar $p$; "
         r"the screen's decision; and whether it matched the sign of $\Delta$ (not "
         r"adopting is right when $\Delta\le0$). Pooled rows: summed counts, with an "
         r"item-cluster bootstrap that draws each task's items once for all of its "
         r"cells. The intervals, $p$-values, and pooled rows are post hoc. Bottom: "
         r"run-to-run reference on the engineering task. The protocol's "
         r"pilot-split results are in Supplementary Table~\ref{tab:S-splits}.}",
         r"\label{tab:predictive}",
         r"\setlength{\tabcolsep}{3.2pt}",
         r"\begin{tabular}{@{}lrrrrrrll@{}}", r"\toprule",
         r"Cell & $n$ & $a$ (\%) & Fixed & Corrupted & $\Delta$ (pts) & "
         r"[95\% CI] & $p$ & Screen: right? \\", r"\midrule"]
    for cid, c in res["cells"].items():
        v = ph["cells"][cid]
        dec = "adopt" if v["screen_adopt"] else "skip"
        T.append(rf"{cellname(c)} & {c['n']} & {pct(c['a'])} & {c['fix']}/{c['n_wrong']} & "
                 rf"{c['cor']}/{c['n_right']} & ${pp(v['delta'])}$ & "
                 rf"[${pp(v['delta_ci'][0])}$, ${pp(v['delta_ci'][1])}$] & "
                 rf"{v['mcnemar_p']:.2f} & {dec}: {'yes' if v['screen_right'] else 'no'} \\")
    T.append(r"\midrule")
    for name, lab in (("high_a", r"$a>\tfrac12$, pooled"), ("low_a", r"$a<\tfrac12$, pooled")):
        g = ph["groups"][name]
        cs = [res["cells"][k] for k in g["cells"]]
        fx, wr = sum(c["fix"] for c in cs), sum(c["n_wrong"] for c in cs)
        co, ri = sum(c["cor"] for c in cs), sum(c["n_right"] for c in cs)
        nright = sum(ph["cells"][k]["screen_right"] for k in g["cells"])
        dec = "adopt" if name == "low_a" else "skip"
        T.append(rf"{lab} ({len(cs)} cells) & {g['n']} & {pct(ri / g['n'])} & {fx}/{wr} & "
                 rf"{co}/{ri} & ${pp(g['delta'])}$ & "
                 rf"[${pp(g['delta_ci'][0])}$, ${pp(g['delta_ci'][1])}$] & & "
                 rf"{dec}: {nright} of {len(cs)} \\")
    if "eng_qwen_debate" in sm and "eng_qwen_ge" in sm:
        d_, g_ = sm["eng_qwen_debate"], sm["eng_qwen_ge"]
        T.append(r"\midrule")
        T.append(r"\multicolumn{9}{@{}p{0.97\linewidth}@{}}{Run-to-run reference, "
                 r"engineering task (final accuracy of the same configuration, same "
                 r"items and seed derivation): DEBATE " + pct(d_["trace_final_acc"]) +
                 r"\% (Apple~M4 trace run) against " + pct(d_["matrix_acc_seed1"]) +
                 r"\% and " + pct(d_["matrix_acc_seed2"]) + r"\% (RTX~4060, seeds 1 and 2); "
                 r"GE " + pct(g_["trace_final_acc"]) + r"\% against " +
                 pct(g_["matrix_acc_seed1"]) + r"\% and " + pct(g_["matrix_acc_seed2"]) +
                 r"\%; final answers matching across the two machines: " +
                 pct(g_["agree_final_seed1"], 0) + r"\% (GE) and " +
                 pct(d_["agree_final_seed1"], 0) + r"\% (DEBATE).} \\")
    T += [r"\bottomrule", r"\end{tabular}", r"\end{table}"]
    with open(os.path.join(outdir, "criterion_predictive_table.tex"), "w") as f:
        f.write("\n".join(T) + "\n")

    # ---- supplement table: the protocol's pilot-split results per cell
    has2 = "acc_R2" in m
    T = [r"% Generated by scripts/criterion_predictive.py; do not edit by hand.",
         r"\begin{table}[t]\centering\scriptsize",
         r"\caption{Pre-specified pilot-split analysis of the out-of-sample test. "
         r"Over " + str(res["n_splits"]) + r" random splits per cell, a pilot of "
         r"$m{=}" + str(res["m"]) + r"$ items gives the prediction and the remaining "
         r"items are held out; the splits of one cell overlap, so they are not "
         r"independent tests. R1 plugs the pilot's $a$, $p_{\mathrm{fix}}$, "
         r"$p_{\mathrm{cor}}$ into Eq.~(1) of the main text; R2 uses the pilot's $a$ "
         r"with $p_{\mathrm{fix}}$, $p_{\mathrm{cor}}$ pooled from the same workflow "
         r"on the other tasks; R3 adopts iff the pilot's $a<\tfrac12$. Accuracy: share "
         r"of splits whose adopt decision matches the sign of the held-out $\Delta$ "
         r"(not adopting is correct when $\Delta\le0$); MAE: mean absolute error of "
         r"the predicted $\Delta$, in points. Bottom rows: means over cells, with the "
         r"baselines.}",
         r"\label{tab:S-splits}",
         r"\setlength{\tabcolsep}{3.5pt}",
         r"\begin{tabular}{@{}lrrrrrr@{}}", r"\toprule",
         r"Cell & $\Delta$ (pts) & \multicolumn{3}{c}{Accuracy (\%)} & "
         r"\multicolumn{2}{c}{MAE (pts)} \\",
         r"\cmidrule(lr){3-5}\cmidrule(l){6-7}",
         r"& & R1 & R2 & R3 & R1 & R2 \\", r"\midrule"]
    for cid, c in res["cells"].items():
        a2 = pct(m["acc_R2_per_cell"][cid], 0) if has2 else "n/a"
        e2 = pct(m["mae_R2_per_cell"][cid]) if has2 else "n/a"
        T.append(rf"{cellname(c)} & ${100*c['delta']:+.1f}$ & "
                 rf"{pct(m['acc_R1_per_cell'][cid], 0)} & {a2} & "
                 rf"{pct(m['acc_R3_a_only_per_cell'][cid], 0)} & "
                 rf"{pct(m['mae_R1_per_cell'][cid])} & {e2} \\")
    T.append(r"\midrule")
    T.append(rf"\multicolumn{{2}}{{@{{}}l}}{{Mean over the {len(m['cells'])} cells}} & "
             rf"{pct(m['acc_R1'])} & {pct(m['acc_R2']) if has2 else 'n/a'} & "
             rf"{pct(m['acc_R3_a_only'])} & "
             rf"{pct(m['mae_R1'])} & {pct(m['mae_R2']) if has2 else 'n/a'} \\")
    T.append(rf"\multicolumn{{2}}{{@{{}}l}}{{Always / never adopt (accuracy)}} & "
             rf"\multicolumn{{5}}{{l}}{{{pct(m['acc_always'])} / {pct(m['acc_never'])}}} \\")
    T.append(rf"\multicolumn{{2}}{{@{{}}l}}{{Predict $\Delta{{=}}0$ / other tasks' "
             rf"pooled $\Delta$ (MAE)}} & \multicolumn{{5}}{{l}}{{{pct(m['mae_ZERO'])}"
             rf" / {pct(m['mae_POOLD']) if has2 else 'n/a'}}} \\")
    T += [r"\bottomrule", r"\end{tabular}", r"\end{table}"]
    with open(os.path.join(outdir, "criterion_splits_table.tex"), "w") as f:
        f.write("\n".join(T) + "\n")

    # ---- supplement table: pooled estimates and pilot-size sensitivity
    ci = lambda a, b, d=2: f"[{num(a, d)}, {num(b, d)}]"
    S = [r"% Generated by scripts/criterion_predictive.py; do not edit by hand.",
         r"\begin{table}[t]\centering\scriptsize",
         r"\caption{Pooled correction/corruption estimates from summed item counts "
         r"(Wilson interval for $a$, transformed to the odds; for $p_{\mathrm{fix}}/p_{\mathrm{cor}}$ the "
         r"Wilson-based MOVER interval and an item-cluster bootstrap interval; for "
         r"the pooled $\Delta$ a cell-stratified item bootstrap, " +
         f"{10000:,}".replace(",", "{,}") + r" resamples), and the decision-rule "
         r"results by pilot size $m$ (" + str(res["n_splits"]) + r" splits per cell).}",
         r"\label{tab:pooled}",
         r"\setlength{\tabcolsep}{2.4pt}",
         r"\begin{tabular}{@{}lrrrrrrrr@{}}", r"\toprule",
         r"Pool & Items & $a$ & $p_{\mathrm{fix}}$ & $p_{\mathrm{cor}}$ & "
         r"Ratio [MOVER] & [Bootstrap] & $a/(1-a)$ [CI] & $\Delta$ (pts) [CI] \\",
         r"\midrule"]
    lab = {"debate": "DEBATE cells", "ge": "GE cells", "all": "All cells",
           "new_cells": "Blind cells"}
    for name, P in res["pooled"].items():
        S.append(rf"{lab[name]} & {P['n']} & {num(P['a'])} & "
                 rf"{num(P['p_fix'])} & {num(P['p_cor'])} & {num(P['ratio'])} "
                 rf"{ci(*P['ratio_ci'])} & {ci(*P['ratio_ci_boot'])} & "
                 rf"{num(P['odds'])} {ci(*P['odds_ci'])} & ${100*P['delta']:+.1f}$ "
                 rf"[${100*P['delta_ci'][0]:+.1f}$, ${100*P['delta_ci'][1]:+.1f}$] \\")
    S += [r"\midrule",
          r"Pilot $m$ & \multicolumn{4}{l}{Acc.\ (\%) R1 / R2} & "
          r"\multicolumn{4}{l}{MAE (pts) R1 / R2 / zero} \\", r"\midrule"]
    for mm, s_ in res["sensitivity_m"].items():
        S.append(rf"{mm} & \multicolumn{{4}}{{l}}{{{pct(s_['acc_R1'])} / "
                 rf"{pct(s_['acc_R2']) if 'acc_R2' in s_ else 'n/a'}}} & "
                 rf"\multicolumn{{4}}{{l}}{{{pct(s_['mae_R1'])} / "
                 rf"{pct(s_['mae_R2']) if 'mae_R2' in s_ else 'n/a'} / {pct(s_['mae_ZERO'])}}} \\")
    S += [r"\bottomrule", r"\end{tabular}", r"\end{table}"]
    with open(os.path.join(outdir, "criterion_pooled_table.tex"), "w") as f:
        f.write("\n".join(S) + "\n")
