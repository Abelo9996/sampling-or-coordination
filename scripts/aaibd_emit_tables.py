"""Emit the table fragments of the AAIBD revision (paper/aaibd/main_aaibd_rev.tex).
No model calls; reads logs and paper/aaibd/revision_stats.json only.

  paper/aaibd/main_table.tex        accuracy [95% CI] and total tokens per query,
                                    from the logs (seed-average within item, item
                                    mean, item bootstrap, B=10,000, numpy seed 0).
                                    MATH SC k=2,4 at the 1024 cap are macros from
                                    paper/aaibd/rerun_macros.tex.
  paper/aaibd/domination_table.tex  noise-aware Pareto table, from
                                    revision_stats.json section A (hierarchical
                                    bootstrap CIs, item-level token CIs).
  paper/aaibd/round0_table.tex      debate round-0 vote vs final vote, from
                                    revision_stats.json section C.
  paper/aaibd/robustness_table.tex  swept / repaired points, from section A.
  paper/aaibd/cost_table.tex        cost models (GSM8K n=80, MATH 1024), from
                                    revision_stats.json section B; MATH SC k=2,4
                                    are macros from rerun_macros.tex.

  python3 scripts/aaibd_emit_tables.py
"""
import json
import os
import sys
from collections import defaultdict

import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from harness import analyze  # noqa: E402

RES = os.path.join(ROOT, "results")
OUTD = os.path.join(ROOT, "paper", "aaibd")
J = json.load(open(os.path.join(OUTD, "revision_stats.json")))

TASKS = [("GSM8K", "gsm8k_matrix.jsonl"), ("MMLU", "mmlu_matrix.jsonl"),
         ("MATH", "math500_trunc.jsonl")]
ROWS = [("SA", "SA"), ("SC_k2", "SC $k{=}2$"), ("SC_k4", "SC $k{=}4$"),
        ("SC_k8", "SC $k{=}8$"), ("SC_k12", "SC $k{=}12$"),
        ("DEBATE_N3_R1", "Debate"), ("GE_R2", "GE"), ("HIER_M3", "HIER")]
LAB = {"SA": "SA", "SC_k2": "SC$_2$", "SC_k4": "SC$_4$", "SC_k8": "SC$_8$",
       "SC_k12": "SC$_{12}$", "DEBATE_N3_R1": "Debate", "GE_R2": "GE",
       "HIER_M3": "HIER", "DEBATE_N2_R1": "Debate $N{=}2$",
       "GE_R1": "GE $R{=}1$", "HIER_M2": "HIER $M{=}2$",
       "GES_R2": "gated GE", "HIERC_M3": "chained HIER",
       "DEBATE_N3_R2": "Debate $R{=}2$"}


def read(fn):
    return [json.loads(l) for l in open(os.path.join(RES, fn)) if l.strip()]


def cells(rows):
    by = defaultdict(lambda: defaultdict(list))
    for r in rows:
        by[r["config"]][r["item_id"]].append(r)
    out = {}
    for c, items in by.items():
        corr = np.array([np.mean([int(r["correct"]) for r in v]) for v in items.values()])
        tok = np.array([np.mean([r["total_tokens"] for r in v]) for v in items.values()])
        lo, hi = analyze._bootstrap_ci(corr, B=10000)
        seeds = sorted({r["seed"] for v in items.values() for r in v})
        out[c] = (100 * corr.mean(), 100 * lo, 100 * hi, tok.mean(), seeds)
    return out


def main_table():
    data = {t: cells(read(f)) for t, f in TASKS}
    L = ["% AUTO-GENERATED by scripts/aaibd_emit_tables.py. Do not edit."]
    for cfg, lab in ROWS:
        line = [lab]
        for t, _ in TASKS:
            if t == "MATH" and cfg in ("SC_k2", "SC_k4"):
                n = {"SC_k2": "Sctwo", "SC_k4": "Scfour"}[cfg]
                line.append(f"\\Math{n}Acc {{\\tiny\\Math{n}CI}} & \\Math{n}Tok")
                continue
            c = data[t].get(cfg)
            if c is None:
                line.append("-- & --")
                continue
            mark = "$^{\\S}$" if len(c[4]) == 1 and cfg != "SA" else ""
            line.append(f"{c[0]:.1f}{mark} {{\\tiny[{c[1]:.0f},{c[2]:.0f}]}} & {c[3]:.0f}")
        L.append(" & ".join(line) + " \\\\")
        if cfg == "SC_k12":
            L.append("\\midrule")
    open(os.path.join(OUTD, "main_table.tex"), "w").write("\n".join(L) + "\n")


def f1(x):
    return f"{x:+.1f}"


def pair(task, s, c):
    for p in J["A"]["tasks"][task]["pairs"]:
        if p["sampling"] == s and p["coord"] == c:
            return p
    raise KeyError((task, s, c))


def verdict(p):
    """Primary (hierarchical) CI; cheaper = lower mean total tokens."""
    h = p["acc_hier"]
    if p["tok_diff"] >= 0:
        return "--"
    if h["lo_pp"] > 0:
        return "R" + ("$^\\dagger$" if p["tok_hi"] >= 0 else "")
    if h["hi_pp"] < 0:
        return "N"
    return "C"


def dom_row(task, s, c, first, tasklab, coordlab, note=""):
    p = pair(task, s, c)
    h = p["acc_hier"]
    return (f"{tasklab if first else ''} & {coordlab} & {LAB[s]}{note} & "
            f"${f1(h['diff_pp'])}$ {{\\tiny$[{f1(h['lo_pp'])},{f1(h['hi_pp'])}]$}} & "
            f"${p['tok_diff']:+.0f}$ {{\\tiny$[{p['tok_lo']:+.0f},{p['tok_hi']:+.0f}]$}} & "
            f"{verdict(p)} \\\\")


def domination_table():
    spec = [
        ("gsm8k_n80", "GSM8K", [("DEBATE_N3_R1", ["SC_k8", "SA"]),
                                ("GE_R2", ["SC_k8", "SC_k4"]),
                                ("HIER_M3", ["SA"])]),
        ("gsm8k_n200", "GSM8K$_{200}$", [("DEBATE_N3_R1", ["SC_k8", "SA"])]),
        ("math_1024", "MATH", [("DEBATE_N3_R1", ["SC_k12", "SC_k8"]),
                               ("GE_R2", ["SC_k8"]),
                               ("HIER_M3", ["SA"])]),
    ]
    L = ["% AUTO-GENERATED by scripts/aaibd_emit_tables.py from revision_stats.json "
         "section A. Do not edit."]
    for ti, (task, tlab, coords) in enumerate(spec):
        if ti:
            L.append("\\midrule")
        first = True
        for co, comps in coords:
            for j, s in enumerate(comps):
                note = "$^{\\S}$" if (task == "math_1024" and s == "SC_k12") else ""
                L.append(dom_row(task, s, co, first, tlab,
                                 LAB[co] if j == 0 else "", note))
                first = False
    open(os.path.join(OUTD, "domination_table.tex"), "w").write("\n".join(L) + "\n")


def round0_table():
    C = J["C"]["tasks"]
    spec = [("gsm8k_n80", "GSM8K", 640), ("math_traces", "MATH", 1024),
            ("mmlu_n80", "MMLU", 640)]
    L = ["% AUTO-GENERATED by scripts/aaibd_emit_tables.py from revision_stats.json "
         "section C. Do not edit."]
    for k, lab, cap in spec:
        t = C[k]
        d = t["final_minus_round0"]
        L.append(f"{lab} & {cap} & {t['n_items']} & {t['round0_majority_acc_pct']:.1f} & "
                 f"{t['final_acc_pct']:.1f} & ${f1(d['diff_pp'])}$ "
                 f"{{\\tiny$[{f1(d['lo_pp'])},{f1(d['hi_pp'])}]$}} & "
                 f"{t['fixed']}/{t['broken']} \\\\")
    open(os.path.join(OUTD, "round0_table.tex"), "w").write("\n".join(L) + "\n")


def cost_table():
    B = J["B"]["tasks"]
    g, m = B["gsm8k_n80"]["configs"], B["math_1024"]["configs"]
    L = ["% AUTO-GENERATED by scripts/aaibd_emit_tables.py from revision_stats.json "
         "section B. Do not edit."]
    for cfg, lab in ROWS:
        if cfg == "DEBATE_N3_R1":
            L.append("\\midrule")
        a = g.get(cfg)
        gs = (f"{a['acc_pct']:.1f} & {a['total_tokens']:.0f} & {a['out_tokens']:.0f} & "
              f"{a['serial_latency_s']:.1f}") if a else "-- & -- & -- & --"
        if cfg in ("SC_k2", "SC_k4"):
            n = {"SC_k2": "Sctwo", "SC_k4": "Scfour"}[cfg]
            ms = f"\\Math{n}Acc & \\Math{n}Out"
        else:
            b = m[cfg]
            mark = "$^{\\S}$" if b["seeds"] == [1] and cfg != "SA" else ""
            ms = f"{b['acc_pct']:.1f}{mark} & {b['out_tokens']:.0f}"
        L.append(f"{lab} & {gs} & {ms} \\\\")
    open(os.path.join(OUTD, "cost_table.tex"), "w").write("\n".join(L) + "\n")


def robustness_table():
    """Swept and repaired GSM8K points: strongest sampling comparator."""
    A = J["A"]["tasks"]["gsm8k_n80"]
    L = ["% AUTO-GENERATED by scripts/aaibd_emit_tables.py from revision_stats.json "
         "section A. Do not edit."]
    cls = A["classification"]
    for co in ["DEBATE_N2_R1", "GE_R1", "HIER_M2", "GES_R2", "HIERC_M3", "DEBATE_N3_R2"]:
        if co in ("DEBATE_N2_R1", "GES_R2"):
            L.append("\\multicolumn{7}{l}{\\emph{%s}} \\\\" % ("Swept" if co == "DEBATE_N2_R1" else "Repaired"))
        cfg = A["configs"][co]
        cl = cls[co]
        rob_h = cl["acc_hier"]["robustly_dominated_by"]
        rob_i = cl["acc_item"]["robustly_dominated_by"]
        if rob_h:
            s, v = rob_h[0], "R"
        elif rob_i:
            s, v = rob_i[0], "R$^{i}$"
        else:
            s, v = cl["acc_hier"]["cheaper_accuracy_not_distinguishable"][-1], "C"
        p = pair("gsm8k_n80", s, co)
        h = p["acc_hier"]
        L.append(f"{LAB[co]} & {cfg['acc_pct']:.1f} & {cfg['tokens']:.0f} & "
                 f"{LAB[s]} & ${f1(h['diff_pp'])}$ {{\\tiny$[{f1(h['lo_pp'])},{f1(h['hi_pp'])}]$}} & "
                 f"${p['tok_diff']:+.0f}$ & {v} \\\\")
    open(os.path.join(OUTD, "robustness_table.tex"), "w").write("\n".join(L) + "\n")


if __name__ == "__main__":
    main_table()
    domination_table()
    round0_table()
    robustness_table()
    cost_table()
    print("wrote main_table.tex, domination_table.tex, round0_table.tex, "
          "robustness_table.tex in", OUTD)
